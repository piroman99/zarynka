for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin5_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plate %s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
