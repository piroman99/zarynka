# -*- coding: utf-8 -*-
"""Пролог, кадр 8 v3 — гидролаборатория: под водой БОЛЬШОЙ межпланетный корабль
в сцепке со спускаемым модулем (правка Ивана 2026-10-31).

Иван про v2: «тут только посадочный модуль, хотелось бы в сцепке с межпланетным.
Он сильно больше. Мы в тизере нечто подобное видели.»
Референсы дизайна — кадры из тизера: `assets/gen/ok_space_ship_0.jpg` (межпланетный
корабль: белый цилиндрический корпус с тонкой красной полосой, конический хвост с
двумя дюзами, четыре широких крыла солнечных батарей) и `ok_x_ship_dock_0.jpg`
(он же в сцепке со стыковочным узлом).

Что в кадре:
  * под водой — МЕЖПЛАНЕТНЫЙ КОРАБЛЬ (в масштабе он огромен: корпус уходит за край
    кадра, заполняет шахту), а на его носу через короткую ферму-переходник
    пристыкован МАЛЕНЬКИЙ спускаемый модуль (конический теплозащитный экран, гранёный
    корпус) — он в разы меньше корабля;
  * бассейн-шахта ~20 м, дна не видно, стенки подсвечены прожекторами, слои глубины;
  * космонавты и водолаз у стыковочного узла — крошечные, для масштаба.

Варианты: A — с бортика, взгляд вниз в шахту, корабль по диагонали, стык ближе к верху;
          B — камера у воды: низ кадра подводный, корпус уходит в темноту шахты.

Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр. Букв в кадре нет — по правилу Ивана.

Запуск: python3 _prolog_p8_v3.py [prolog_p8v3_a prolog_p8v3_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

GEN = os.path.join(HERE, "assets", "gen")
REF_SHIP = os.path.join(GEN, "ok_space_ship_0.jpg")     # корабль из тизера
REF_DOCK = os.path.join(GEN, "ok_x_ship_dock_0.jpg")    # он же в сцепке

STYLE = (
    "ретро-футуристическая документальная кинохроника альтернативного 2061 года, кадр из фильма, "
    "16:9, киноплёнка с зерном и лёгкими царапинами, приглушённая холодная палитра, живописный "
    "фотореализм, светлый и оптимистичный мир будущего. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, логотипов и водяных знаков — ни на корпусе "
    "корабля, ни на модуле, ни на стенах, ни на приборах, ни на плакатах."
)

HALL = (
    "Зал гидролаборатории Центра подготовки космонавтов — тот же светлый индустриальный мир "
    "будущего, что и цех сборки: высокие стены, фермы под потолком, прожекторы, круглые мостки "
    "с перилами по бортику, лебёдки, шланги, пульт управления. В центре зала КРУГЛАЯ "
    "бассейн-шахта диаметром около двадцати метров и глубиной ОКОЛО ДВАДЦАТИ МЕТРОВ: вода "
    "уходит вниз в сине-зелёную темноту, дна не видно, стенки шахты подсвечены прожекторами "
    "через равные промежутки, поэтому читаются слои глубины. "
)

SHIP = (
    "Под водой подвешен огромный МАКЕТ МЕЖПЛАНЕТНОГО КОРАБЛЯ того же типа, что на приложенных "
    "кадрах: длинный белый цилиндрический корпус с тонкой красной полосой по борту, конический "
    "хвостовой отсек с двумя большими дюзами, четыре широких крыла солнечных батарей из тёмных "
    "панелей, носовой стыковочный узел на короткой ферме. Корабль ОГРОМЕН: его корпус не "
    "помещается в кадр, уходит за край и вниз, в тёмную глубину шахты. "
)

LANDER = (
    "К носовому стыковочному узлу корабля пристыкован МАЛЕНЬКИЙ СПУСКАЕМЫЙ МОДУЛЬ — "
    "межпланетный посадочный аппарат с широким коническим теплозащитным экраном, гранёным "
    "корпусом из охристо-марсианских и графитовых панелей, панорамными окнами, радиаторными "
    "рёбрами, посадочными опорами и дюзами. Он В РАЗЫ МЕНЬШЕ корабля — как катер у лайнера. "
    "ЭТО НЕ советский «Союз»: нет сферы с пристыкованным цилиндром и ряда круглых иллюминаторов. "
)

DIVERS = (
    "У стыковочного узла работают двое космонавтов в белых скафандрах с длинными шлангами, "
    "рядом водолаз-страхующий с фонарём; от них вверх тянутся цепочки пузырей, в воде виден "
    "луч фонаря и мелкая взвесь. Фигурки крошечные рядом с корпусом корабля — по ним читается "
    "масштаб. Наверху, на бортике, несколько человек у перил, тоже крошечные. "
)

A = HALL + SHIP + LANDER + DIVERS + (
    "Камера стоит на бортике и смотрит вниз в шахту: корабль висит по диагонали, стыковочный "
    "узел со спускаемым модулем ближе к верху кадра, хвост с дюзами уходит в тёмную глубину. "
)
B = HALL + SHIP + LANDER + DIVERS + (
    "Камера у самой поверхности воды: нижняя половина кадра подводная, корабль с пристыкованным "
    "спускаемым модулем освещён прожекторами шахты и уходит вниз в темноту, верхняя половина — "
    "зал, мостки и люди над водой. "
)

JOBS = [
    ("prolog_p8v3_a", A),
    ("prolog_p8v3_b", B),
]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    refs = [r for r in (REF_SHIP, REF_DOCK) if os.path.exists(r)]
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        if refs:
            opts["input_base64"] = [gen.b64(r, max_w=1024) for r in refs]
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-18s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-18s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-18s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))