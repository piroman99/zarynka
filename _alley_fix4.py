    "горизонтальны, колени согнуты под прямым углом, ступни стоят на земле, спина прямая, "
    "чуть ссутулился, руки лежат на бёдрах. В кадре фигура целиком — от макушки до ступней, "
    "по центру кадра, с небольшим запасом сверху и снизу. НИКАКИХ НАДПИСЕЙ. "
