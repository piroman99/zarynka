# -*- coding: utf-8 -*-
"""CG «сникшая Екатерина в кресле» — кандидаты в 16:9 для кадра vn2 (стр. 48 приёмной).

Референсы: мастер печального спрайта (лицо) + утверждённая приёмная (сцена/стиль).
Модели: gpt-image-2 (держит лицо по образцу) и nano-banana-2.1 (до 10 референсов).
"""
import os, sys
import gen, pv

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_KATE = os.path.join(HERE, "assets", "gen", "kate_sad_0.png")
REF_ROOM = os.path.join(HERE, "assets", "gen", "kate_reception_vn_0.png")

STYLE = (
    "Стиль японской визуальной новеллы: чистый выразительный лайн-арт, плоская cel-раскраска "
    "с мягкими градиентами, тёплая приглушённая пастельная палитра, спокойное рассеянное "
    "освещение, аккуратные тени. НЕ фотореализм, НЕ 3D, НЕ кинематографично. "
)

CHAR = (
    "Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до подбородка, "
    "яркие голубые глаза, мягкое доброе лицо с лёгкими морщинками, стройная; синий рабочий "
    "комбинезон на лямках поверх светлой рубашки. Сохрани ЛИЦО и манеру рисования точно как "
    "на прикреплённом образце персонажа. "
)

NO_TEXT = ("Без текста, без надписей, без букв, без плакатов с надписями, без водяных знаков. ")

SCENES = {
    # A: главный кандидат — сникшая, на краю кресла, куратор в расфокусе
    "cg_sad_a": (
        "CG-кадр визуальной новеллы 16:9: кабинет приёмной комиссии советского космического центра. "
        + CHAR +
        "Она сникла: сидит на самом краю кожаного кресла перед письменным столом, плечи опущены, "
        "взгляд потухший, смотрит вниз, руки безвольно лежат на коленях. Чуть позади, за столом, "
        "молодой куратор Сергей в форменной светлой рубашке с погонами — он виден в три четверти "
        "со спины и не в фокусе, опустил глаза. Мягкий тёплый вечерний свет из окна, стеллаж с "
        "папками, папка с документами лежит на столе. " + STYLE + NO_TEXT
    ),
    # B: та же сцена, но крупнее — камера ближе, кресло и руки в кадре
    "cg_sad_b": (
        "CG-кадр визуальной новеллы 16:9, средний план: " + CHAR +
        "Она сидит на краю кресла в кабинете приёмной комиссии, вся сжалась, плечи опущены, "
        "голова чуть наклонена, потухший взгляд в пол, пальцы сцеплены на коленях. Позади неё "
        "размытый силуэт стола, стеллажа с папками и окна с вечерним светом. " + STYLE + NO_TEXT
    ),
    # C: со стороны Сергея — она маленькая в кадре, давит пустота комнаты
    "cg_sad_c": (
        "CG-кадр визуальной новеллы 16:9: вид из-за плеча молодого куратора, сидящего за "
        "письменным столом приёмной комиссии. На переднем плане его плечо и край стола с раскрытой "
        "папкой документов, дальше — " + CHAR +
        "Она сникла в кресле напротив: опущенные плечи, потухший взгляд в пол, руки на коленях. "
        "Тихий вечерний свет, приглушённые тёплые тона, много воздуха. " + STYLE + NO_TEXT
    ),
}

REF_MODE = {
    "cg_sad_a": "kate",
    "cg_sad_b": "kate",
    "cg_sad_c": "kate",
}


def b64s(path):
    return gen.b64(path, max_w=1024)


def main(only=None):
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        mode = REF_MODE[name]
        model = os.environ.get("CG_MODEL", "gpt-image-2")
        if model == "nano-banana-2.1":
            opts = {"aspect_ratio": "16:9", "resolution": "1K",
                    "image_base64": [b64s(REF_KATE), b64s(REF_ROOM)]}
        else:
            opts = {"aspect_ratio": "16:9", "resolution": "1K", "image_base64": b64s(REF_KATE)}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %-18s %s RUB" % (name, model, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model),
                                             max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:220]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None)
