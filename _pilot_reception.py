# -*- coding: utf-8 -*-
"""Пустая приёмная в акварели (без людей) — чтобы вся серия была в одной манере."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv
from gen import b64

REF = os.path.join(HERE, "assets", "pilot", "pilot_s_enter_0.png")
OUT = os.path.join(HERE, "assets", "pilot")

STYLE = (
    "АКВАРЕЛЬНАЯ иллюстрация для визуальной новеллы: прозрачные акварельные заливки по "
    "белой бумаге, мягкие потёки, неровные края, местами бумага остаётся нетронутой, "
    "видимое зерно бумаги, лёгкий карандашный контур. Ограниченная палитра: пыльно-синий, "
    "тёплая охра и золото, светлый серый, много белого воздуха. Мягкий рассеянный свет. "
    "НЕ фотореализм, НЕ 3D-рендер, НЕ плотная гуашь, НЕ глянец, НЕ кинематографическая "
    "темнота, без тяжёлых чёрных теней и без грязной живописи."
)

PROMPT = (
    "Акварельная иллюстрация, ФОН визуальной новеллы. Приёмная комиссия советского "
    "космического центра, ранняя весна. В КАДРЕ НЕТ ЛЮДЕЙ в комнате — пустая приёмная; "
    "ЛЮДИ ВИДНЫ ТОЛЬКО ЗА ОКНОМ, на улице, вдалеке и нерезко.\n\n"
    "ОКРУЖЕНИЕ: простой письменный стол со стороны посетителя — на нём раскрытые папки "
    "и авторучка; два обычных стула для посетителей; сбоку приставной столик с папками. "
    "Большое окно во всю стену: яркий весенний день, мокрый асфальт, ели, за стеклом "
    "длинная очередь людей с папками, они ждут и переговариваются. В глубине — открытая "
    "дверь в коридор с белым светом. На стене — один скромный плакат про дальний полёт; "
    "стены почти пустые, светлые, краска чуть облуплена.\n\n"
    "ВАЖНО: НЕТ карты Луны, НЕТ модели лунного модуля, НЕТ настольной лампы, НЕТ "
    "кожаного начальственного кресла — это не кабинет начальника, а обычная приёмная, "
    "где принимают документы.\n\n"
    "КОМПОЗИЦИЯ: широкий кадр 16:9, стол в нижней трети, центр свободен (там встанет "
    "фигура), много воздуха, место для текста внизу.\n\n"
    "НАСТРОЕНИЕ: тихое весеннее утро, надежда, длинная очередь к мечте."
)


def main():
    model = sys.argv[1] if len(sys.argv) > 1 else "gpt-image-2"
    opts = {"aspect_ratio": "16:9", "resolution": "2K",
            "image_base64": b64(REF, max_w=760)}
    prompt = PROMPT + "\n\nСТИЛЬ: " + STYLE
    q = pv.price(model, prompt, opts)
    print("смета:", q.get("priceRub"), "₽", flush=True)
    files, st = pv.generate_to_files(model, prompt, opts, outdir=OUT,
                                     name="pilot_reception", max_price_rub=15)
    print("файлы:", files, "цена:", st.get("priceRub"), "₽", flush=True)


main()
