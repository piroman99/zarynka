"""S4 (комната/телевизор) — 2 варианта. Правки заказчика:
  • НЕ семидесятые: комната и техника — 2061, современный ЦВЕТНОЙ экран
  • на экране — КОСМОС/МАРС (цветное, не «синие полосы»)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая тёплая палитра, "
         "живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, "
         "НИКАКОГО текста, надписей, букв, цифр, логотипов и водяных знаков.")

JOBS = {
 's4_a': ("Жилая комната в космическом городке, 2061 год: современная светлая гостиная с "
          "панорамным окном, на стене большой тонкий цветной экран-панель; на экране — яркое "
          "цветное изображение космоса и красной планеты Марс, звёзды. Мягкий вечерний свет, "
          "удобное кресло, низкий столик, комнатные растения, лаконичная мебель будущего. "
          "Уютно, тепло, современно — НЕ интерьер 1970-х годов."),
 's4_b': ("Светлая жилая комната в Звёздном городке, 2061 год: на стене широкий цветной "
          "экран-панель, показывающий цветную передачу про космос — орбитальная станция и "
          "красная планета Марс на фоне звёзд. Рядом кресло, торшер тёплого света, полка с "
          "книгами и моделями ракет, растения; современный лаконичный интерьер будущего, "
          "вечерний уют. НЕ ретро 1970-х."),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin3_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plate %s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("flux-2", prompt, {"aspect_ratio": "16:9", "resolution": "2K"},
                                     outdir="assets/gen", name='prologfin3_%s' % n, max_price_rub=12)
    print('plate %s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE), st.get('priceRub')))
print('готово')
