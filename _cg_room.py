# -*- coding: utf-8 -*-
"""CG «сникшая Екатерина» В НАШЕЙ приёмной и В НАШЕМ стиле.

Референсы (input_base64):
  1) assets/pilot/pilot_reception_0.png — настоящий фон приёмной из vn2 (комната + стиль),
  2) assets/gen/kate_sad_0.png — лицо/одежда героини.
Задача: комната ровно как на первом референсе, ракурс сверху-сбоку, Екатерина сникла в кресле.
"""
import os, sys
import gen, pv

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_ROOM = os.path.join(HERE, "assets", "pilot", "pilot_reception_0.png")
REF_KATE = os.path.join(HERE, "assets", "gen", "kate_sad_0.png")

STYLE = (
    "Стиль и манера рисования — ТОЧНО как на приложенном кадре интерьера: тот же чистый лайн-арт, "
    "та же плоская cel-раскраска, та же приглушённая пастельная палитра, то же спокойное "
    "рассеянное освещение, та же толщина контуров. Ничего не менять в манере. "
)
ROOM = (
    "Интерьер — РОВНО тот же, что на приложенном кадре приёмной: те же окна с видом на площадь "
    "и ели, та же дверь в коридор, тот же письменный стол с раскрытыми документами и ручкой, "
    "тот же плакат на стене, тот же стеллаж с синими папками, тот же цвет стен с облупившейся "
    "краской. Ничего не добавлять и не убирать из обстановки. "
)
KATE = (
    "В кадре — Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до "
    "подбородка, яркие голубые глаза, мягкое доброе лицо с лёгкими морщинками, синий рабочий "
    "комбинезон на лямках поверх светлой рубашки (лицо и одежда — как на втором референсе). "
)
SAD = (
    "Она сникла: сидит на стуле с синей обивкой перед письменным столом, плечи опущены, голова "
    "наклонена, потухший взгляд вниз, руки безвольно лежат на коленях. "
)
NO_TEXT = "Никаких новых надписей, букв и водяных знаков. "

SCENES = {
    # A — повтор кадра, который понравился: сверху-сбоку, через стол
    "cg_room_a": (
        "CG-кадр визуальной новеллы 16:9, тот же кабинет приёмной, но с ДРУГИМ ракурсом. " + ROOM
        + KATE + SAD +
        "РАКУРС: камера высоко и сбоку — смотрит СВЕРХУ ВНИЗ под углом около 40 градусов, из-за "
        "края письменного стола; по диагонали нижнего плана идёт край стола с раскрытыми "
        "документами, за ним видно её опущенные плечи, колени и наклонённую голову, лицо в три "
        "четверти, взгляд вниз. " + STYLE + NO_TEXT
    ),
    # B — тот же ракурс, но камера ближе: она крупнее, стол только по нижнему краю
    "cg_room_b": (
        "CG-кадр визуальной новеллы 16:9, тот же кабинет приёмной, крупнее. " + ROOM + KATE + SAD +
        "РАКУРС: камера сверху-сбоку, наклон вниз около 35 градусов, ближе к ней: она занимает "
        "центральную часть кадра, видны спинка стула, её плечи, руки на коленях и опущенное лицо "
        "в три четверти; по нижнему краю — срез стола с папкой. " + STYLE + NO_TEXT
    ),
    # C — сверху и чуть сзади-сбоку: затылок, ссутуленная спина, стол впереди
    "cg_room_c": (
        "CG-кадр визуальной новеллы 16:9, тот же кабинет приёмной. " + ROOM + KATE + SAD +
        "РАКУРС: камера сверху и сзади-сбоку, за её левым плечом, наклон вниз около 35 градусов: "
        "видно затылок с седыми кудрями, ссутуленную спину, руки на коленях, а впереди — край стола "
        "с раскрытой папкой документов; лицо в профиль-три-четверти, взгляд вниз. "
        + STYLE + NO_TEXT
    ),
}


def main(only=None, model="gpt-image-2"):
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        opts = {"aspect_ratio": "16:9", "resolution": "1K",
                "input_base64": [gen.b64(REF_ROOM, max_w=1024), gen.b64(REF_KATE, max_w=768)]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %-14s %s RUB" % (name, model, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:220]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("CG_MODEL", "gpt-image-2"))
