def main():
    opts = {"aspect_ratio": "16:9", "resolution": "2K"}
    from gen import b64
    opts["image_base64"] = b64(REF, max_w=760)

    model = sys.argv[1] if len(sys.argv) > 1 else "gpt-image-2"
    prompt = PROMPT + "\n\nСТИЛЬ: " + STYLE
    q = pv.price(model, prompt, opts)
    print("модель:", model, "смета:", q.get("priceRub"), "₽", flush=True)

    files, st = pv.generate_to_files(model, prompt, opts, outdir=OUT,
                                     name="pilot_s_enter", max_price_rub=15)
    print("файлы:", files, flush=True)
    print("цена:", st.get("priceRub"), "₽", flush=True)


main()
