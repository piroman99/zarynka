"""S3-c — настроение: ОЗАБОЧЕННЫЕ, но НЕ грустные (слушают важный вопрос).
Не смеются, не рыдают — сосредоточенные, внимательные, чуть напряжённые лица.
Атмосфера прежнюю (светлый зал, знамёна, гражданская одежда) СОХРАНЯЕМ.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая тёплая палитра, "
         "живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, "
         "НИКАКОГО текста, надписей, букв, цифр, логотипов и водяных знаков.")

MOOD = ("Психология лиц: люди ОЗАБОЧЕННЫЕ и СОСРЕДОТОЧЕННЫЕ, но НЕ грустные — "
        "внимательные задумчивые лица, слегка сдвинутые брови, слушают важное и неожиданное, "
        "в глазах надежда и вопрос. НЕ улыбаются широко, НЕ смеются, НЕ хохочут, "
        "но и НЕ печальные, НЕ скорбные. Сдержанное человеческое раздумье.")

JOBS = {
 's3_c': ("Светлый просторный зал Дома культуры советского космического городка 2061 года, "
          "большое открытое собрание: просторный зал с высокими окнами и тёплым золотистым светом. "
          "Много людей в разнообразной гражданской одежде — рубашки, светлые платья, пиджаки, "
          "галстуки, кто-то с ребёнком. Люди повёрнуты в три четверти, видно лица. "
          "Красные знамёна и алые полотнища без надписей над сценой. "
          "Атмосфера серьёзного народного собрания, где решается судьба, "
          "всенародное внимание и надежда."),
 's3_d': ("Праздничный, но сдержанный зал советского Дома культуры, 2061 год: много людей, "
          "внимательно слушающих выступающего с трибуны; лица в три четверти, сосредоточенные, "
          "задумчивые, обеспокоенные неожиданным вопросом, но с тёплой надеждой во взгляде; "
          "разнообразная гражданская одежда тёплых тонов, кто-то с ребёнком; красные знамёна и "
          "алые транспаранты без букв, тёплый свет. Собранность и человечность, без уныния "
          "и без бурного веселья."),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin3_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plane %s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\n" + MOOD + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("flux-2", prompt, {"aspect_ratio": "16:9", "resolution": "2K"},
                                     outdir="assets/gen", name='prologfin3_%s' % n, max_price_rub=12)
    print('plane %s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE), st.get('priceRub')))
print('готово')
