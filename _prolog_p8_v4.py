# -*- coding: utf-8 -*-
"""Пролог, кадр 8 v4 — правка принятого B: на межпланетном корабле добавить остекление.

Иван (2026-10-31): «Вариант B норм. Не нравится только что на межпланетном модуле нет
иллюминаторов или не знаю, лобовых стекол, как правильно сказать?»

Значит: композиция B сохраняется один-в-один (бассейн-шахта, корабль в диагональ,
пристыкованный спускаемый модуль, космонавты у стыка), добавляем только ОСТЕКЛЕНИЕ:
  * лента лобового остекления командного отсека в носовой части корабля (широкие
    трапециевидные окна с перемычками, тёплый свет внутри);
  * ряд круглых иллюминаторов вдоль корпуса по красной полосе.

Два варианта подачи (на выбор Ивана):
  A — сдержанно: только командный отсек со лентой лобовых окон + редкие иллюминаторы;
  B — выразительно: плюс второй ряд иллюминаторов по жилому отсеку и подсвеченные окна.

Генерация — редактирование принятого кадра (`prolog_p8v3_b`) с референсом корабля из
тизера. gpt-image-2, 16:9 1K = 4.06 ₽/кадр.

Запуск: python3 _prolog_p8_v4.py [prolog_p8v4_a prolog_p8v4_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

GEN = os.path.join(HERE, "assets", "gen")
REF_BASE = os.path.join(GEN, "prolog_p8v3_b__gpt-image-2_0.png")   # принятый кадр B
REF_SHIP = os.path.join(GEN, "ok_space_ship_0.jpg")                # дизайн корабля из тизера

STYLE = (
    "Тот же кадр, та же композиция, тот же свет и та же палитра, что на первом референсе — "
    "это ПРАВКА существующего кадра, а не новый кадр. Ретро-футуристическая документальная "
    "кинохроника альтернативного 2061 года, 16:9, киноплёнка с зерном, приглушённая холодная "
    "палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, логотипов и водяных знаков — ни на корпусе "
    "корабля, ни на модуле, ни на стекле, ни на стенах, ни на приборах."
)

KEEP = (
    "СОХРАНИТЬ БЕЗ ИЗМЕНЕНИЙ: зал гидролаборатории, круглый бассейн-шахту глубиной около "
    "двадцати метров с подсвеченными стенками и уходящей в темноту водой, положение и ракурс "
    "межпланетного корабля, пристыкованный к его носу маленький спускаемый модуль с коническим "
    "теплозащитным экраном, двух космонавтов в скафандрах со шлангами и водолаза у стыковочного "
    "узла, пузыри, взвесь в воде, мостки и людей на бортике наверху. "
)

GLASS = (
    "ДОБАВИТЬ только остекление корабля: в носовой части, сразу за стыковочным узлом, — "
    "ЛЕНТА ЛОБОВОГО ОСТЕКЛЕНИЯ командного отсека: ряд широких трапециевидных окон с тонкими "
    "перемычками, тёмные снаружи и с тёплым желтоватым светом внутри, как рубка большого "
    "корабля. Вдоль белого корпуса по линии красной полосы — РЯД КРУГЛЫХ ИЛЛЮМИНАТОРОВ в "
    "утопленных окантовках, ровный шаг, часть с тёплым светом, часть тёмных. Стекло не "
    "зеркалит, не блестит рекламно: мутноватое от воды, с отражениями прожекторов шахты. "
)

A = GLASS + (
    "Сдержанно: лента лобовых окон командного отсека и ОДИН ряд иллюминаторов по корпусу, "
    "дальше корпус уходит в темноту без окон. "
)
B = GLASS + (
    "Выразительнее: лента лобовых окон командного отсека, ряд иллюминаторов по корпусу и "
    "второй ряд по жилому отсеку ниже, у большей части окон тёплый свет внутри — видно, "
    "что корабль обитаемый. "
)

JOBS = [("prolog_p8v4_a", A), ("prolog_p8v4_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    refs = [r for r in (REF_BASE, REF_SHIP) if os.path.exists(r)]
    if not refs:
        raise SystemExit("нет референсов")
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + KEEP + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K",
                "input_base64": [gen.b64(r, max_w=1024) for r in refs]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-18s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-18s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-18s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))