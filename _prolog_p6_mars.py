# -*- coding: utf-8 -*-
"""Пролог, кадр 6 — ПЕРЕДЕЛКА: хроника ПЕРВОЙ марсианской экспедиции, кадры С МАРСА.

Иван 2026-10-25: «Переделай первый. Там скорее кадры с марса нужны...» — вместо проводов
на космодроме нужен архивный кадр с поверхности Марса (Первая экспедиция уже слетала,
см. story.txt: «Один раз были?»).

Варианты:
  A — общий: посадочный корабль на красной равнине, крошечные фигуры экипажа, кратеры.
  B — крупнее: двое в старых скафандрах идут по пыли, следы, корабль силуэтом позади.

Плёнка ЗАМЕТНО старше остальных кадров пролога: выцвело, тёпло-серое, крупное зерно,
царапины и пылинки. Букв/флагов с надписями/эмблем в кадре НЕТ (правило Ивана).
Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

STYLE = (
    "ретро-футуристическая документальная кинохроника, кадр из архивного фильма о первой "
    "марсианской экспедиции, 16:9, киноплёнка: сильное зерно, мелкие царапины, пылинки, "
    "лёгкая расфокусировка по краям, выцветшая тёпло-серая палитра, живописный фотореализм. "
    "НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, НЕ постер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, эмблем, логотипов и водяных знаков — "
    "ни на корабле, ни на скафандрах, ни на флагах, ни в небе."
)

# ------------------------------------------------------------------ A · общий
P6A = (
    "Архивный кадр кинохроники с поверхности Марса. Красная каменистая равнина, мелкий "
    "гравий и пыль, редкие камни, вдалеке невысокие обрывы и старый кратер. Справа в кадре "
    "стоит посадочный марсианский корабль: приземистый цилиндрический корпус на четырёх "
    "опорах, потемневшие от пыли теплозащитные панели, короткая посадочная ступень, "
    "антенна-штырь. Рядом с кораблём — три крошечные фигуры космонавтов в светлых "
    "скафандрах, для масштаба; от корабля к ним тянутся цепочки следов на пыли. "
    "Небо пыльно-жёлтое, без облаков и без звёзд, солнце низко и мутно. Ветер поднимает "
    "лёгкую дымку у горизонта. Ощущение документальной съёмки: камера стоит на штативе, "
    "чуть завалена, край кадра мягкий."
)

# ------------------------------------------------------------------ B · крупнее
P6B = (
    "Архивный кадр кинохроники с поверхности Марса, средний план. Двое космонавтов в "
    "старых громоздких светлых скафандрах с большими круглыми иллюминаторами идут по "
    "красной пыли друг за другом, оставляя глубокие цепочки следов; у одного на спине "
    "небольшой контейнер с приборами, в руке штанга с датчиком. Позади них, в мутной "
    "дымке, силуэт посадочного корабля на опорах. Вокруг каменистая равнина, мелкие "
    "камни, следы колёс ровера в пыли. Небо пыльно-жёлтое, низкое мутное солнце, "
    "длинные тени от фигур. Съёмка с рук, чуть смазано, зерно и царапины плёнки."
)

JOBS = [
    # A (общий план) выбран НЕ был — Иван взял B, кадр лежит в assets/rejected/p6/.
    # Оставлен в списке, чтобы можно было вернуться к нему вручную: python3 _prolog_p6_mars.py prolog_p6_mars_a
    ("prolog_p6_mars_a", P6A),
    ("prolog_p6_mars_b", P6B),
]


def main(only=None, model="gpt-image-2"):
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-20s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-20s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-20s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))
