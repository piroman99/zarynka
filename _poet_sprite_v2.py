# -*- coding: utf-8 -*-
"""Поэт Лёша Савушкин — спрайт v2: НЕ аниме, округлое лицо, лёгкая небритость.

Правка Ивана 2026-11-04: «он какой-то слишком анимешный вышел. В моём воображении у него
чуть более округлое лицо, лёгкая небритость. Цвет волос, ну ок, тёмный».

Поэтому:
  • стиль — как у принятого каста (`kate_overalls_0.png`, gpt-image-2): мягкая живопись
    / полуреализм, а не galge-лайн-арт; референс подаётся картинкой;
  • лицо ОКРУГЛОЕ, мягкие щёки, без «острого подбородка» и больших аниме-глаз;
  • лёгкая небритость (щетина 1-2 дня), тёмные волосы, длинная плохая причёска.

Канон 2016 (`old:Sprites`): «Должен появляться в двух видах. С длинной плохой прической и
аккуратно стриженный»; эмоции с волосами — нормальный, заинтересованный, расстроенный.
Текст (стр. 19): «длинноволосый поэт, высокий, нескладный, с тоской в больших серых глазах».

Варианты:
  A — сидит/стоит прямо, потерянное выражение, волосы на плечах
  B — чуть вполоборота, голова опущена, прядь падает на лицо

Запуск:
    python3 _poet_sprite_v2.py [poet2_a poet2_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv  # noqa: E402

REF = os.path.join(HERE, 'assets', 'gen', 'kate_overalls_0.png')   # принятый спрайт каста

LOOK = (
    "Портрет-спрайт персонажа визуальной новеллы: МОЛОДОЙ МУЖЧИНА примерно 25 лет, поэт. "
    "Лицо ОКРУГЛОЕ и мягкое: полные щёки, округлый подбородок, короткий нос, глаза "
    "обычного размера — БЕЗ больших аниме-глаз, без заострённого подбородка, без "
    "«красавчика». На щеках и над губой ЛЁГКАЯ НЕБРИТОСТЬ, щетина на день-два, "
    "не ухоженная. Глаза серые, взгляд потерянный и тоскливый, брови чуть приподняты. "
    "Волосы ТЁМНЫЕ, длинные и неухоженные, спадают на плечи неровными прядями. "
    "Высокий, нескладный, узкие плечи, чуть сутулится. Одежда простая и мешковатая: "
    "тёмная куртка поверх светлой рубашки, без знаков, без надписей, без украшений. "
    "Поясной спрайт (видно до середины бедра), фигура по центру, ровный однотонный "
    "светло-серый фон, без реквизита, без тени на фон. "
    "Манера рисования и степень реализма — ТОЧНО как на приложенном спрайте: мягкая "
    "живопись, объёмное лицо, видимые мазки и зерно, натуральные пропорции. "
    "НЕ аниме, НЕ манга, НЕ galge, НЕ cel-shading, НЕ 3D-рендер, НЕ фото."
)

A = LOOK + (" Стоит прямо, руки свободно опущены, смотрит в камеру — расстроенный, "
            "растерянный, готовый расплакаться.")
B = LOOK + (" Стоит чуть вполоборота, голова опущена, одна прядь волос падает на лицо, "
            "плечи опущены — поза потерянного человека.")

JOBS = [("poet2_a", A), ("poet2_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    ref = gen.b64(REF, max_w=1024)
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core
        opts = {"aspect_ratio": "3:4", "resolution": "1K", "input_base64": [ref]}
        q = pv.price(model, prompt, opts)
        print("[quote] %-8s %s RUB" % (name, q.get("priceRub")), flush=True)
        if dry:
            continue
        try:
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name=name, max_price_rub=12)
            print("[ok] %-8s %s" % (name, [os.path.basename(f) for f in files]), flush=True)
        except Exception as e:  # noqa: BLE001
            print("[fail] %-8s %s" % (name, str(e)[:160]), flush=True)


if __name__ == "__main__":
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    main(only or None)
