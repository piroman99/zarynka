# -*- coding: utf-8 -*-
"""P4 v2 — CG «двое в приёмной» на страницу 35 (SCRIPT_CAST.md), держится до 37.

Правки Ивана 2026-10-25 к прошлому P4:
  1) кабинет — НАШ (референс = принятый CG приёмной cg_room_a), а не выдуманный;
  2) одежда Сергея — со спрайта (форменная рубашка с погонами, тёмный галстук);
  3) вид за окном — весна, ели, низкие корпуса Звёздного городка.
Бит кадра: «Сергей потер переносицу, подбирая слова, чтобы не обидеть собеседницу» —
ему тяжело, она ещё надеется. НЕ приветствие, улыбок нет.

Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр.
"""
import os, sys
import gen, pv
import _cg_rec23 as R          # ROOM / KATE / SERGEY / WINDOW / STYLE / NO_TEXT

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_ROOM = R.REF_ROOM
REF_SERGEY = R.REF_SERGEY

# P4: Сергей отвёл взгляд и трёт переносицу — заменяем «приветственную» позу
SERGEY_P4 = (
    "Сергей Лихнецкий: мужчина 30 лет, короткие тёмные волосы с лёгкой сединой на висках, "
    "светлые глаза, чисто выбрит, ОДЕЖДА — как на втором приложенном кадре: светлая форменная "
    "рубашка с погонами на плечах и тёмный галстук. Он сидит за письменным столом, отвёл взгляд "
    "в сторону, двумя пальцами потирает переносицу — ему тяжело подбирать слова; улыбки нет, "
    "брови сведены. Перед ним закрытая зелёная папка с документами и ручка. "
)
KATE_P4 = (
    "Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до подбородка, яркие "
    "голубые глаза, мягкое доброе лицо с лёгкими морщинками, синий рабочий комбинезон на лямках "
    "поверх светлой рубашки. Она сидит на стуле с синей обивкой перед столом, спина прямая, руки "
    "на коленях, смотрит на Сергея внимательно и ещё с надеждой — без улыбки, без слёз. "
)

SCENES = {
    # A — средний план со стороны стола: оба в три четверти, папка между ними
    "cg_p4v2_a": (
        "CG-кадр визуальной новеллы 16:9: тяжёлый разговор в приёмной комиссии. "
        + R.ROOM + SERGEY_P4 + KATE_P4 + R.WINDOW +
        "РАКУРС: средний план от окна, камера чуть выше уровня стола. Сергей справа за столом, "
        "Екатерина слева на стуле, между ними по диагонали край стола с закрытой папкой. Оба лица "
        "хорошо читаются. " + R.STYLE + R.NO_TEXT
    ),
    # B — через плечо Екатерины на Сергея: ближе к POV, её затылок в кадре
    "cg_p4v2_b": (
        "CG-кадр визуальной новеллы 16:9: тяжёлый разговор в приёмной комиссии. "
        + R.ROOM + SERGEY_P4 + KATE_P4 + R.WINDOW +
        "РАКУРС: через плечо Екатерины — на переднем плане её плечо и седые кудри в расфокусе, "
        "в фокусе Сергей за столом, отводящий взгляд и трущий переносицу. Средний план. "
        + R.STYLE + R.NO_TEXT
    ),
}


def main(only=None, model="gpt-image-2"):
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        opts = {"aspect_ratio": "16:9", "resolution": "1K",
                "input_base64": [gen.b64(REF_ROOM, max_w=1024),
                                 gen.b64(REF_SERGEY, max_w=1024)]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("CG_MODEL", "gpt-image-2"))
