"""Пролог, кадр 8 v2 — гидролаборатория ЦПК (переделка по правке Ивана 2026-10-31).

Иван про старый кадр (`prolog_p8_pool__gpt-image-2_0.png`):
«там какой-то старый модуль от союза ещё, хочется что-то пофутуристичнее
марсоподобное и бассейн поглубже».

Что меняем:
  * макет под водой — НОВЫЙ МЕЖПЛАНЕТНЫЙ СПУСКАЕМЫЙ МОДУЛЬ марсианской экспедиции:
    конический теплозащитный экран, гранёный корпус, охристо-марсианские и графитовые
    панели, панорамные окна, радиаторные рёбра, посадочные опоры и дюзы, стыковочный
    узел сверху. Прямой запрет: советский «Союз» (сфера + цилиндр, ряд иллюминаторов);
  * бассейн ГЛУБЖЕ: шахта ~20 м, дно не видно, вода уходит в сине-зелёную темноту,
    стенки шахты подсвечены прожекторами — читаются слои глубины;
  * макет висит на глубине ~12 м, космонавты и водолаз — вокруг него, пузыри вверх.

Варианты: A — с бортика, камера чуть сверху (видно всю глубину);
          B — камера у самой воды, нижняя половина кадра подводная.

Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр. Букв в кадре нет — по правилу Ивана.

Запуск: python3 _prolog_p8_v2.py [prolog_p8v2_a prolog_p8v2_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

GEN = os.path.join(HERE, "assets", "gen")

STYLE = (
    "ретро-футуристическая документальная кинохроника альтернативного 2061 года, кадр из фильма, "
    "16:9, киноплёнка с зерном и лёгкими царапинами, приглушённая холодная палитра, живописный "
    "фотореализм, светлый и оптимистичный мир будущего. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, логотипов и водяных знаков — ни на корпусе "
    "модуля, ни на стенах, ни на приборах, ни на плакатах."
)

HALL = (
    "Зал гидролаборатории Центра подготовки космонавтов — тот же светлый индустриальный мир "
    "будущего, что и цех сборки: высокие стены, фермы под потолком, прожекторы, мостки. "
    "В центре зала КРУГЛЫЙ бассейн-шахта диаметром около двадцати метров и ГОЛУБОКОЙ ГЛУБИНОЙ "
    "ОКОЛО ДВАДЦАТИ МЕТРОВ: вода уходит вниз в сине-зелёную темноту, дна не видно, стенки шахты "
    "подсвечены прожекторами через равные промежутки, поэтому читаются слои глубины и уходящие "
    "вниз тени. "
)

MODULE = (
    "На глубине примерно двенадцать метров под водой подвешен ПОЛНОРАЗМЕРНЫЙ МАКЕТ НОВОГО "
    "МЕЖПЛАНЕТНОГО СПУСКАЕМОГО МОДУЛЯ марсианской экспедиции: снизу широкий конический "
    "теплозащитный экран, выше футуристический гранёный корпус из крупных панелей — тёмно-"
    "графитовых и охристо-марсианских, с панорамными окнами, радиаторными рёбрами-плавниками, "
    "четырьмя посадочными опорами и дюзами по кругу, сверху стыковочный узел с кольцом. "
    "ЭТО НЕ советский «Союз»: нет сферы с пристыкованным цилиндром, нет ряда круглых "
    "иллюминаторов, нет бытового отсека — только новый марсианский корабль. "
)

DIVERS = (
    "Двое космонавтов в белых скафандрах с длинными шлангами работают у модуля на глубине, "
    "рядом водолаз-страхующий с фонарём, от аквалангов вверх тянутся цепочки пузырей, в воде "
    "виден луч фонаря и мелкая взвесь. По бортику круглые мостки с перилами, лебёдки, шланги, "
    "пульт управления; блики и отражения на поверхности воды, лёгкая дымка над ней. "
)

A = HALL + MODULE + DIVERS + (
    "Камера стоит на бортике чуть сверху: видно, как модуль уходит далеко вниз, вокруг него "
    "тёмная глубина шахты, а наверху светлый зал с людьми у перил (крошечные для масштаба). "
)
B = HALL + MODULE + DIVERS + (
    "Камера у самой поверхности воды: нижняя половина кадра — подводная, модуль в глубине "
    "освещён прожекторами шахты, верхняя половина — зал, мостки и люди над водой. "
)

JOBS = [
    ("prolog_p8v2_a", A),
    ("prolog_p8v2_b", B),
]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        try:
            if dry:
                q = pv.price(model, prompt, opts)
                print("[quote] %-18s %s RUB" % (name, q.get("priceRub")), flush=True)
                continue
            q = pv.price(model, prompt, opts)
            print("[quote] %-18s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-18s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-18s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))