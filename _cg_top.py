# -*- coding: utf-8 -*-
"""CG «сникшая Екатерина в кресле» — ВИД СВЕРХУ-СБОКУ (высокий ракурс через стол).
Три композиции: мягкий наклон, крутая верхняя точка, «сверху и чуть сзади».
"""
import os, sys
import gen, pv

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_KATE = os.path.join(HERE, "assets", "gen", "kate_sad_0.png")

STYLE = (
    "Стиль японской визуальной новеллы: чистый выразительный лайн-арт, плоская cel-раскраска "
    "с мягкими градиентами, тёплая приглушённая пастельная палитра, спокойное рассеянное "
    "освещение, аккуратные тени. НЕ фотореализм, НЕ 3D, НЕ кинематографично. "
)

CHAR = (
    "Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до подбородка, "
    "яркие голубые глаза, мягкое доброе лицо с лёгкими морщинками, стройная; синий рабочий "
    "комбинезон на лямках поверх светлой рубашки. Сохрани ЛИЦО и манеру рисования точно как "
    "на прикреплённом образце персонажа. "
)

NO_TEXT = "Без текста, без надписей, без букв, без водяных знаков. "

ROOM = ("Кабинет приёмной комиссии советского космического центра: тяжёлый письменный стол "
        "с зелёным сукном, стеллаж с папками, окно с мягким дневным светом. ")

SAD = ("Она сникла: сидит в кресле, плечи опущены, голова наклонена, потухший взгляд вниз, "
       "руки безвольно лежат на коленях. ")

SCENES = {
    # A: высокий ракурс сверху-сбоку, камера над столом смотрит вниз на кресло
    "cg_top_a": (
        "CG-кадр визуальной новеллы 16:9. " + ROOM + CHAR + SAD +
        "РАКУРС: камера высоко, чуть сбоку — смотрит СВЕРХУ ВНИЗ, из-за края письменного стола, "
        "под углом примерно 40 градусов. Видны спинка и подлокотник кресла сверху, колени и "
        "опущенные плечи, макушка и лицо в три четверти снизу-вверх не видно — лицо обращено вниз. "
        "На переднем плане по диагонали край стола с раскрытой папкой документов. "
        + STYLE + NO_TEXT
    ),
    # B: почти вертикально сверху, стол и кресло читаются как пятна света
    "cg_top_b": (
        "CG-кадр визуальной новеллы 16:9. " + ROOM + CHAR + SAD +
        "РАКУРС: камера почти вертикально СВЕРХУ, наклон вниз около 60 градусов, сдвинута вбок. "
        "В кадре сверху видны: макушка с седыми кудрями, плечи, колени, носки туфель; "
        "кресло крупным тёмным пятном, край стола и папка по нижнему краю кадра. "
        "Свет мягко ложится сверху, тени уходят вниз-влево. "
        + STYLE + NO_TEXT
    ),
    # C: сверху и чуть сзади-сбоку — видно затылок и ссутуленную спину
    "cg_top_c": (
        "CG-кадр визуальной новеллы 16:9. " + ROOM + CHAR + SAD +
        "РАКУРС: камера сверху и сзади-сбоку, за её левым плечом, наклон вниз около 35 градусов: "
        "видно затылок с седыми кудрями, ссутуленную спину, руки на коленях и край стола впереди; "
        "лицо в профиль-три-четверти, взгляд вниз, на столе перед ней раскрытая папка с документами. "
        + STYLE + NO_TEXT
    ),
}


def main(only=None, model="gpt-image-2"):
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        opts = {"aspect_ratio": "16:9", "resolution": "1K", "image_base64": gen.b64(REF_KATE, max_w=1024)}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-9s %-14s %s RUB" % (name, model, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-9s %s RUB -> %s" % (name, st.get("priceRub"),
                                              os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-9s %s" % (name, str(e)[:220]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("CG_MODEL", "gpt-image-2"))
