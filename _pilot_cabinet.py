# -*- coding: utf-8 -*-
"""Фон для флешбэка: кабинет Старика, ПУСТОЙ (спрайт движок положит сверху).
Стиль тот же акварельный, что в пилоте — референс берём из pilot_s_enter_0.png."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv
from gen import b64

REF = os.path.join(HERE, "assets", "pilot", "pilot_s_enter_0.png")   # держим манеру
OUT = os.path.join(HERE, "assets", "pilot")
os.makedirs(OUT, exist_ok=True)

STYLE = (
    "АКВАРЕЛЬНАЯ иллюстрация для визуальной новеллы: прозрачные акварельные заливки по "
    "белой бумаге, мягкие потёки, неровные края, местами бумага остаётся нетронутой, "
    "видимое зерно бумаги, лёгкий карандашный контур. Ограниченная палитра: пыльно-синий, "
    "тёплая охра и золото, светлый серый, много белого воздуха. Мягкий рассеянный свет. "
    "НЕ фотореализм, НЕ 3D-рендер, НЕ плотная гуашь, НЕ глянец, НЕ кинематографическая "
    "темнота, без тяжёлых чёрных теней и без грязной живописи."
)

PROMPT = (
    "Акварельная иллюстрация, ФОН визуальной новеллы. Кабинет начальника в советском "
    "космическом центре, зима, раннее утро. В КАДРЕ НЕТ ЛЮДЕЙ — полностью пустая комната, "
    "ни одного человека, ни силуэта.\n\n"
    "ОКРУЖЕНИЕ: массивный рабочий стол из тёмного дерева, на нём раскрытые папки с "
    "бумагами, авторучка, стакан с чаем, телефонный аппарат с диском, модель лунного "
    "модуля на подставке. За столом — высокое окно с морозными узорами по краю, за окном "
    "заснеженный парк, тёмные ели в снегу. На стене — большая карта Луны с трассами "
    "посадочных площадок, рядом чертёж орбиты, нарисованный от руки, и полка с книгами и "
    "папками. Кожаное кресло отодвинуто, будто хозяин только что вышел.\n\n"
    "КОМПОЗИЦИЯ: широкий кадр 16:9, место для персонажа слева и для текста внизу. "
    "Холодный зимний свет из окна, тёплый настольная лампа.\n\n"
    "НАСТРОЕНИЕ: строгий, холодный, чуть раздражённый кабинет — сюда вызывают на выговор."
)


def main():
    model = sys.argv[1] if len(sys.argv) > 1 else "gpt-image-2"
    opts = {"aspect_ratio": "16:9", "resolution": "2K",
            "image_base64": b64(REF, max_w=760)}
    prompt = PROMPT + "\n\nСТИЛЬ: " + STYLE
    q = pv.price(model, prompt, opts)
    print("модель:", model, "смета:", q.get("priceRub"), "₽", flush=True)
    files, st = pv.generate_to_files(model, prompt, opts, outdir=OUT,
                                     name="pilot_cabinet", max_price_rub=15)
    print("файлы:", files, "цена:", st.get("priceRub"), "₽", flush=True)


main()
