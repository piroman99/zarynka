# -*- coding: utf-8 -*-
"""P4 v3 — CG «двое в приёмной» (стр. 35 SCRIPT_CAST.md), Сергей ОДИН В ОДИН со спрайта.

Правка Ивана 2026-10-25: в v2 Сергей был выбрит и в галстуке, а на спрайте он НЕБРИТЫЙ,
в тёмном рабочем жилете и с бейджем «ИНЖЕНЕР». Совмещаем: персонаж = спрайт
(лицо, щетина, жилет, бейдж), сцена = наш кабинет (cg_room_a), весна за окном.

Бит кадра: «Сергей потер переносицу, подбирая слова, чтобы не обидеть собеседницу» —
ему тяжело, она ещё надеется. Не приветствие, улыбок нет.

Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр.
"""
import os, sys
import gen, pv
import _cg_rec23 as R

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_ROOM = R.REF_ROOM
REF_SERGEY = R.REF_SERGEY
# тесный кроп спрайта (лицо + щетина + жилет + бейдж) — сильнее держит детали
REF_SERGEY_CROP = os.path.join(HERE, "assets", "gen", "_ref_sergey_face_0.png")


def make_crop():
    from PIL import Image
    im = Image.open(REF_SERGEY)
    w, h = im.size
    box = (int(w * 0.06), int(h * 0.00), int(w * 0.94), int(h * 0.86))
    c = im.crop(box)
    c.save(REF_SERGEY_CROP)
    return REF_SERGEY_CROP

# Единственная надпись, которую разрешаем модели — слово на бейдже
TEXT_OK = (
    "Из надписей в кадре — ТОЛЬКО слово «ИНЖЕНЕР» на бейдже Сергея, печатными буквами, "
    "мелко и аккуратно. Никаких других надписей, букв, цифр и водяных знаков: ни на плакате, "
    "ни на папке, ни на документах, ни на стене. "
)

SERGEY_P4 = (
    "Сергей Лихнецкий — ОДИН В ОДИН как на втором и третьем приложенных кадрах (это его спрайт): мужчина "
    "30–35 лет, короткие тёмно-русые волосы с проседью на висках, светлые глаза, ЛЁГКАЯ "
    "НЕБРИТОСТЬ — короткая щетина на подбородке, щеках и над верхней губой (он НЕ чисто выбрит, "
    "бритья нет). Одежда ровно та же, что на спрайте: тёмно-графитовый рабочий жилет с накладными "
    "карманами и молнией поверх светло-бежевой рубашки с подвёрнутыми рукавами, на шее тёмно-синий "
    "шнурок, на груди прямоугольный бейдж. Галстука НЕТ, погон НЕТ, форменного кителя НЕТ. "
    "Он сидит за письменным столом, отвёл взгляд в сторону, двумя пальцами потирает переносицу — "
    "ему тяжело подбирать слова; улыбки нет, брови сведены. Перед ним закрытая зелёная папка "
    "с документами и ручка. "
)
KATE_P4 = R.KATE  # Екатерина — как в принятом CG приёмной
KATE_P4 = (
    "Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до подбородка, яркие "
    "голубые глаза, мягкое доброе лицо с лёгкими морщинками, синий рабочий комбинезон на лямках "
    "поверх светлой рубашки. Она сидит на стуле с синей обивкой перед столом, спина прямая, руки "
    "на коленях, смотрит на Сергея внимательно и ещё с надеждой — без улыбки, без слёз. "
)

SCENES = {
    # A — средний план со стороны окна: оба в три четверти, папка между ними
    "cg_p4v3_a": (
        "CG-кадр визуальной новеллы 16:9: тяжёлый разговор в приёмной комиссии. "
        + R.ROOM + SERGEY_P4 + KATE_P4 + R.WINDOW +
        "РАКУРС: средний план от окна, камера чуть выше уровня стола. Сергей справа за столом, "
        "Екатерина слева на стуле, между ними по диагонали край стола с закрытой папкой. Оба лица "
        "хорошо читаются, но лицо и одежда Сергея — главное. " + R.STYLE + TEXT_OK
    ),
    # B — через плечо Екатерины на Сергея: её плечо в расфокусе, Сергей в фокусе
    "cg_p4v3_b": (
        "CG-кадр визуальной новеллы 16:9: тяжёлый разговор в приёмной комиссии. "
        + R.ROOM + SERGEY_P4 + KATE_P4 + R.WINDOW +
        "РАКУРС: через плечо Екатерины — на переднем плане её плечо и седые кудри в расфокусе, "
        "в фокусе Сергей за столом, отводящий взгляд и трущий переносицу. Средний план. "
        + R.STYLE + TEXT_OK
    ),
}

def main(only=None, model="gpt-image-2"):
    crop = make_crop()
    print("[ref] %s" % os.path.relpath(crop, HERE), flush=True)
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        opts = {"aspect_ratio": "16:9", "resolution": "1K",
                "input_base64": [gen.b64(REF_ROOM, max_w=1024),
                                 gen.b64(REF_SERGEY, max_w=1024),
                                 gen.b64(crop, max_w=1024)]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                            name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:240]), flush=True)

if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("CG_MODEL", "gpt-image-2"))
