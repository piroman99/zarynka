# -*- coding: utf-8 -*-
"""Зарянка: ЛИСТ ПЕРСОНАЖА + СЕРИЯ ИЗ 5 СЦЕН одной сцены («Приёмная комиссия»).
Движок консистентности — nano-banana-2.1, референс — утверждённая Екатерина.
Печатаем по мере готовности (flush), запускать в фоновой сессии.
"""
import os, sys, gen, pv

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF = os.path.join(HERE, "assets", "gen", "kate_overalls_0.png")
MODEL = "nano-banana-2.1"

CHAR = (
    "женщина 68 лет, короткие седые ВЬЮЩИЕСЯ волосы (мягкие пружинящие кудри до подбородка), "
    "яркие голубые глаза, мягкое доброе лицо с лёгкими морщинками, спокойная тёплая полуулыбка, "
    "стройная; одета в синий рабочий комбинезон на лямках поверх светлой рубашки. "
)
STYLE = ("Стиль аниме-визуальной новеллы (гальгэ): чистый выразительный лайн-арт, плоская "
         "cel-раскраска, мягкая пастельная палитра, спокойный свет, без фотореализма и 3D. ")

# ---------- 1) ЛИСТ ПЕРСОНАЖА (одна картинка, 4 ракурса) ----------
SHEET = (
    "Лист персонажа (character sheet) для визуальной новеллы: ОДИН И ТОТ ЖЕ персонаж показан "
    "четыре раза в ряд — анфас, три четверти, профиль, со спины (по пояс). " + CHAR +
    "Сохрани ЛИЦО, причёску и манеру рисования точно как на прикреплённом образце. "
    "Ровный однотонный светло-серый фон, аккуратная сетка. " + STYLE
)

# ---------- 2) СЕРИЯ ИЗ 5 СЦЕН — биты сцены «Приёмная комиссия» ----------
SCENES = [
    ("c1_enters",  "Кадр визуальной новеллы: Екатерина Ивановна входит в кабинет приёмной комиссии, "
                   "остановилась у двери, прижимает к груди папку с документами, спокойна и приветлива. "
                   "Фон: кабинет советского космического центра, стол, стеллаж с папками. Полный рост по колено."),
    ("c2_papers",  "Кадр визуальной новеллы: Екатерина Ивановна протягивает раскрытую папку с документами "
                   "через письменный стол куратору (куратор виден со спины, не в фокусе). Мягкая полуулыбка. "
                   "Фон: кабинет приёмной комиссии."),
    ("c3_face",    "Крупный план лица Екатерины Ивановны за столом: говорит мягким мелодичным голосом, "
                   "тёплый открытый взгляд, лёгкий наклон головы, доброжелательная полуулыбка. Плечи и грудь в кадре."),
    ("c4_sits",    "Кадр визуальной новеллы: Екатерина Ивановна сидит на краю кресла в приёмной, руки на коленях, "
                   "слушает внимательно и спокойно, лёгкая усталая улыбка. Фон: кабинет приёмной комиссии."),
    ("c5_sad",     "Кадр визуальной новеллы: Екатерина Ивановна сникла — плечи опущены, взгляд потухший, "
                   "грустные брови, уголки губ вниз, смотрит вниз. Сидит на краю кресла. "
                   "Фон: кабинет приёмной комиссии, приглушённый свет."),
]


def render(name, prompt, ref=True, ar="3:4"):
    opts = {"aspect_ratio": ar, "resolution": "1K"}
    if ref:
        opts["image_base64"] = gen.b64(REF)
    try:
        q = pv.price(MODEL, prompt, opts)
        print(f"[quote] {name:12s} {q.get('priceRub')} ₽", flush=True)
        files, st = pv.generate_to_files(MODEL, prompt, opts, outdir="assets/gen",
                                         name=f"sheet_{name}" if name.startswith("char") else f"series_{name}",
                                         max_price_rub=12)
        print(f"[OK] {name:12s} {st.get('priceRub')} ₽ -> {os.path.relpath(files[0], HERE)}", flush=True)
    except Exception as e:
        print(f"[FAIL] {name:12s} {str(e)[:180]}", flush=True)


print("=== ЛИСТ ПЕРСОНАЖА ===", flush=True)
render("char_sheet", SHEET + " Сохрани лицо персонажа как на образце.", ref=True, ar="16:9")

print("=== СЕРИЯ 5 СЦЕН ===", flush=True)
for tag, prompt in SCENES:
    render(tag, prompt + " " + CHAR + "Сохрани ЛИЦО, причёску и манеру рисования точно как "
           "на прикреплённом образце. " + STYLE)

print("ALL DONE", flush=True)
