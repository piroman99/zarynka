def render(name, ar, prompt, with_ref):
    opts = {"aspect_ratio": ar, "resolution": "1K"}
    if with_ref:
        opts["image_base64"] = gen.b64(REF)
    full = prompt if not with_ref else prompt
    full = full + "\n\nСТИЛЬ: " + STYLE
    try:
        q = pv.price(MODEL, full, opts)
        print(f"[quote] {name:14s} {q.get('priceRub')} ₽", flush=True)
        files, st = pv.generate_to_files(MODEL, full, opts, outdir="assets/gen",
                                         name=f"ok_{name}", max_price_rub=12)
        print(f"[OK] {name:14s} {st.get('priceRub')} ₽ -> {os.path.relpath(files[0], HERE)}", flush=True)
    except Exception as e:
        print(f"[FAIL] {name:14s} {str(e)[:200]}", flush=True)


