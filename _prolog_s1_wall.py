# -*- coding: utf-8 -*-
"""Пролог, кадр S1 — НОВЫЙ кадр «Звёздный городок, стена, полустёртое граффити».

Решение Ивана 2026-11-04 (развилка A): первый кадр пролога — стена в Звёздном
городке с полустёртым граффити «МАРС — ДЕЛО ОБЩЕЕ»; подворотня (старый кадр s1)
остаётся на ВТОРОЙ странице, между ними бесплатный кроссфейд .bg 0.6 с.

Текст L[5] делится по фразе «Очень уж хотелось поймать»:
  стр. 1 — «Кто бросил клич „Марс — дело общее“? …часть работников Звездного городка.»
  стр. 2 — «Очень уж хотелось поймать этого умника в темной подворотне…» → подворотня

Буквы ВНУТРИ кадра — только силами модели (правило Ивана): граффити рисует
gpt-image-2, своих пририсовок на стене не делаем. Других надписей в кадре нет
(ни табличек, ни афиш, ни номеров).

Варианты:
  A — крупно, фрунтально: стена во весь кадр, граффити большое, левая часть смыта.
  B — шире: угол двора, стена в среднем плане, весенний свет, одна фигура спиной.

gpt-image-2, 16:9 1K ≈ 4.06 ₽/кадр. Запуск:
    python3 _prolog_s1_wall.py [s1wall_a s1wall_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

STYLE = (
    "Ретро-футуристическая документальная кинохроника альтернативного 2061 года, 16:9, "
    "кадр из фильма, киноплёнка с мелким зерном и лёгкими царапинами, приглушённая "
    "холодная палитра, живописный фотореализм. Весна, день, мягкий солнечный свет, "
    "длинные косые тени. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, НЕ постер."
)

LETTERS = (
    "На стене ОДНА надпись, нанесённая аэрозольной краской от руки, крупными печатными "
    "буквами кириллицей, в две строки: сверху «МАРС — ДЕЛО», снизу «ОБЩЕЕ». Это ГРАФФИТИ: "
    "краска с потёками, края букв рваные, местами стена просвечивает; надпись ПОЛУСТЁРТА — "
    "её пытались смыть: слева широкая смытая полоса, разводы, мокрые потёки, местами "
    "буквы смазаны и наполовину стёрты, но слова ещё читаются. "
    "БОЛЬШЕ НИКАКИХ НАДПИСЕЙ В КАДРЕ НЕТ: ни табличек, ни указателей, ни афиш, ни "
    "номеров домов, ни цифр, ни логотипов, ни водяных знаков, ни надписей на одежде."
)

A = (
    "Стена дома в Звёздном городке во весь кадр, съёмка фрунтально, камера на уровне "
    "груди. Старая оштукатуренная стена серо-песочного цвета с потёртостями, у земли "
    "полоса цоколя и грязный снег не нужен — весна, сухой асфальт, у стены растёт "
    "чахлая трава. Граффити крупно, в центре и чуть левее, занимает среднюю треть "
    "кадра. Слева от надписи — широкая смытая полоса: стена светлее, краска размазана "
    "тряпкой. У стены на асфальте стоит ведро с мутной водой и лежит мокрая тряпка. "
    "Справа в кадр заходит угол здания и водосточная труба. Людей нет. "
) + LETTERS

B = (
    "Угол двора в Звёздном городке: длинная стена одноэтажной пристройки уходит в "
    "перспективу вправо, слева низкий забор и весенние деревья без листвы, за ними "
    "пятиэтажный жилой корпус. Граффити на стене в средней части кадра, чуть меньше "
    "трети ширины. Одна фигура в куртке идёт вдоль стены спиной к камере, для масштаба. "
    "Солнце сбоку, длинные тени от деревьев и забора лежат на асфальте. "
) + LETTERS

JOBS = [("s1wall_a", A), ("s1wall_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))
