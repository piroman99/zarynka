"""S6 на gpt-image-2 — та же модель, что рисовала приёмную (там кириллица вышла правильно).
Правка Ивана 2026-10-17: «очень мало людей, ну какая это очередь» -> настоящая длинная очередь.

A: широкий план — арка КПП с вывеской «ЗВЁЗДНЫЙ ГОРОДОК», длинная очередь уходит в глубину.
B: средний план — очередь крупно, люди вплотную, арка и будка за ними.
Стиль тот же: светлая тёплая кинохроника 2061, рассвет, снег, пар от дыхания.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая тёплая оптимистичная "
         "палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер.")

TEXT = ("На широкой панели над аркой крупная надпись кириллицей строго: «ЗВЁЗДНЫЙ ГОРОДОК» — "
        "буквы ровные, без ошибок и без искажений. Другого текста, цифр и логотипов в кадре нет.")

CROWD = ("У ворот стоит ДЛИННАЯ, ПЛОТНАЯ ОЧЕРЕДЬ людей — несколько десятков человек, "
         "она тянется от турникета и уходит далеко в глубину кадра, изгибаясь вдоль ограды; "
         "люди стоят вплотную друг к другу, кто-то с сумкой, кто-то с ребёнком за руку, "
         "кто-то с термосом, у многих пар от дыхания на морозе. Очередь — главное в кадре, "
         "людей МНОГО, это не пустой тротуар. Люди 2061 года в чистой современной спокойной "
         "одежде, никакой кожи, рванья и «девяностых».")

JOBS = {
 'a': ("Раннее утро, рассвет: низкое солнце даёт тёплую золотистую полосу у горизонта, небо "
       "светлое, морозная дымка, лёгкий снег на асфальте. Широкий общий план въезда в "
       "Звёздный городок 2061 года: монументальная светлая железобетонная арка-проезд над "
       "дорогой, под ней шлагбаум и прозрачная кабина-турникет, рядом стеклянная будка "
       "вахтёра, в будке человек в форме. За аркой в глубине светлые корпуса городка и "
       "тонкая мачта с антенной. " + CROWD),
 'b': ("Раннее утро, рассвет, тёплая золотистая полоса у горизонта, морозная дымка. Средний "
       "план: очередь людей крупно, люди занимают почти весь кадр, стоят плечом к плечу "
       "перед турникетом и шлагбаумом; за ними монументальная светлая арка-проезд КПП "
       "Звёздного городка 2061 года и стеклянная будка вахтёра. Видны лица в три четверти, "
       "спокойные и сосредоточенные, у многих пар от дыхания, на плечах снег. " + CROWD),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 's6_gpt_%s_0.jpg' % n)
    if os.path.exists(out):
        print('s6 gpt%s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\n" + TEXT + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("gpt-image-2", prompt, {"aspect_ratio": "16:9"},
                                     outdir="assets/gen", name='s6_gpt_%s' % n,
                                     max_price_rub=6)
    print('s6 gpt%s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE),
                                        st.get('priceRub')))
print('готово')
