"""Перегенерация ТОЛЬКО пробы S1 (советский двор) — flux-2. ~4.74 ₽."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с зерном и лёгкими царапинами, приглушённая "
         "холодная палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, "
         "НИКАКОГО текста, надписей, букв, цифр, логотипов и водяных знаков.")

name = "prolog_s1_cin"
core = ("Советская глухая подворотня глухой ночью, захламлённый двор: облупленная кирпичная "
        "стена с осыпавшейся штукатуркой, тёмная арка во двор, ржавая водосточная труба, "
        "голая лампочка на проводе тускло светит, покосившиеся мусорные контейнеры, лужа и "
        "чугунный люк на асфальте, одинокий силуэт человека в кепке у стены. Неухоженно, менее "
        "аккуратно, чем западный двор, атмосфера тайны, глубокая тень. Холодная сине-серая палитра.")
prompt = core + "\n\nСТИЛЬ: " + CHRON
opts = {"aspect_ratio": "16:9", "resolution": "2K"}
q = pv.price("flux-2", prompt, opts)
print(f"[{name}] quote={q.get('priceRub')} ₽")
files, st = pv.generate_to_files("flux-2", prompt, opts, outdir="assets/gen",
                                 name=name, max_price_rub=12)
print(f"  OK -> {os.path.relpath(files[0], HERE)}  price={st.get('priceRub')}")
print(f"  balance={pv.balance()}")
