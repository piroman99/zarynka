# -*- coding: utf-8 -*-
"""Две правки Ивана (2026-11-10): скамейка «перерисовать» + улыбка поэта «перегенерить».

1) bench2 — НОВЫЙ проп-скамейка. Что не так со старым (замер `_bench_orient.py`):
   верхняя кромка спинки 0.1°, нижняя -2.7° — скамейка нарисована ПОЧТИ ФРОНТАЛЬНО,
   то есть поперёк аллеи. В кадре аллея уходит в глубину к воротам, значит длина
   скамейки должна уходить в глубину вправо-вверх, ближний торец крупнее.
   Референс — кадр аллеи (стиль/свет/цвет), 1 картинка = 0.45 ₽.

2) sit2_smile2 — эмоция «сдержанная надежда» вместо открытой улыбки.
   Референс — эталон позы `sit2_neutral_0.png` (1 картинка = 0.45 ₽).

Запуск: python3 _alley_fix5.py [bench2 sit2_smile2] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv  # noqa: E402

GEN = os.path.join(HERE, 'assets', 'gen')
ALLEY = os.path.join(GEN, 'alley_b_0.jpg')
SITREF = os.path.join(GEN, 'sit2_neutral_0.png')

BENCH_PROMPT = (
    "Акварельный рисунок ОДНОГО предмета: старая парковая деревянная скамейка со спинкой, "
    "ЦЕЛИКОМ в кадре, длинная — на четыре места, без людей, БЕЗ аллеи, без деревьев, "
    "без травы и без ворот. "
    "РАЗВОРОТ (главное): скамейка стоит ВДОЛЬ дорожки, её длина уходит в глубину "
    "ВПРАВО-ВВЕРХ под углом около 12 градусов к горизонту; ближний торец крупный и низкий, "
    "дальний торец меньше и выше — перспектива сходится к точке в правом верхнем углу. "
    "Мы видим её спереди-справа и чуть сверху: видно плоскость сиденья, спинка из трёх "
    "горизонтальных реек уходит влево-вверх, ножки простые деревянные. "
    "Дерево выветренное, серо-коричневое, потёртости, мокрые потёки. "
    "Фон — ровный однотонный светло-серый, без тени на фон. Кадр плотно по скамейке. "
    "Манера и палитра — как на приложенном кадре аллеи: акварель, прозрачные заливки по "
    "белой бумаге, видимое зерно, пыльно-синий + охра + белый, мягкие растушёвки. "
    "НЕ 3D, НЕ глянец, НЕ фото, НЕ аниме. НИКАКИХ НАДПИСЕЙ."
)

SMILE_LOCK = (
    "Тот же персонаж, та же манера: молодой мужчина двадцати пяти лет, округлое мягкое лицо, "
    "полные щёки, короткий нос, серые глаза, лёгкая небритость, тёмные длинные неухоженные "
    "волосы до плеч, тёмная куртка поверх светлой рубашки. Мягкая живопись, видимые мазки, "
    "как на приложенном спрайте. НЕ аниме, НЕ 3D, НЕ фото. "
)
SMILE_POSE = (
    " Он СИДИТ на скамейке, но СКАМЕЙКИ В КАДРЕ НЕТ: под ним и за ним пусто, ровный "
    "однотонный светло-серый фон, без тени на фон. Поза сидящего человека: бёдра "
    "горизонтальны, колени согнуты под прямым углом, ступни на земле, спина прямая, "
    "чуть ссутулился, руки лежат на бёдрах. В кадре фигура целиком — от макушки до ступней, "
    "по центру кадра. НИКАКИХ НАДПИСЕЙ. "
)
SMILE_EXPR = (
    " Выражение — СДЕРЖАННАЯ НАДЕЖДА, а не радость: уголки губ едва подняты, губы сомкнуты, "
    "глаза смотрят вверх-вбок и мягко светятся, брови чуть приподняты, лицо спокойное и "
    "собранное. НЕ широкая улыбка, НЕ оскал, НЕ восторг, зубы не видны, щёки не растянуты."
)

JOBS = [
    ('bench2', BENCH_PROMPT, {'aspect_ratio': '16:9', 'resolution': '1K',
                              'input_base64': [gen.b64(ALLEY, max_w=1024)]}),
    ('sit2_smile2', SMILE_LOCK + SMILE_POSE + SMILE_EXPR,
     {'aspect_ratio': '3:4', 'resolution': '1K',
      'input_base64': [gen.b64(SITREF, max_w=900)]}),
]

only = [a for a in sys.argv[1:] if not a.startswith('-')]
dry = '--dry' in sys.argv
tot = 0.0
for name, prompt, opts in JOBS:
    if only and name not in only:
        continue
    q = pv.price('gpt-image-2', prompt, opts)
    price = float(q.get('priceRub') or 0)
    tot += price
    print('[quote] %-13s %.2f RUB' % (name, price), flush=True)
    if dry:
        continue
    try:
        files, st = pv.generate_to_files('gpt-image-2', prompt, opts, outdir='assets/gen',
                                         name=name, max_price_rub=6)
        print('[ok]    %-13s %s' % (name, [os.path.basename(f) for f in files]), flush=True)
    except Exception as e:  # noqa: BLE001
        print('[fail]  %-13s %s' % (name, str(e)[:200]), flush=True)
print('[sum] %.2f RUB' % tot)
