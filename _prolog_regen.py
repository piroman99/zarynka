def sheet(fname, title, items):
    pad, caph, hdr, gap = 20, 44, 82, 10
    cw = 1920
    rh = round(items[0][0].height * cw / items[0][0].width)
    H = hdr + len(items) * (rh + caph + gap) + pad
    c = Image.new('RGB', (cw + 2 * pad, H), (13, 14, 19)); d = ImageDraw.Draw(c)
    d.text((pad, 16), title, font=ImageFont.truetype(LATO_B, 26), fill=(226, 186, 104))
    y = hdr
    for im, cap in items:
        r = im.resize((cw, rh), Image.LANCZOS)
        c.paste(r, (pad, y)); d.rectangle([pad, y, pad + cw, y + rh], outline=(60, 62, 74))
        d.text((pad + 4, y + rh + 7), cap, font=ImageFont.truetype(LATO_B, 21), fill=(240, 236, 228))
        y += rh + caph + gap
    c.save(os.path.join(REV, fname))
    print('sheet ->', os.path.relpath(os.path.join(REV, fname), HERE), c.size)


