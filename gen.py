    ap.add_argument("--res", default=None)
    ap.add_argument("--model", default="flux-2")
    ap.add_argument("--simple", action="store_true",
                    help="стиль «попроще» (ретро-гальгэ, ровные заливки)")
    a = ap.parse_args()
    run(a.name, ref=a.ref, ar=a.ar, res=a.res, model=a.model, simple=a.simple)
