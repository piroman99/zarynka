def b64(path, max_w=760):
    """Референс в data-URI; крупные файлы ужимаем, чтобы не раздувать запрос."""
    try:
        from PIL import Image
        import io
        im = Image.open(path).convert("RGBA")
        if im.width > max_w:
            im = im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "PNG", optimize=True)
        data = buf.getvalue()
    except Exception:
        data = open(path, "rb").read()
    return "data:image/png;base64," + base64.b64encode(data).decode()


def run(name, ref=None, ar=None, res=None, extra_style=True, model="flux-2", simple=False):
    spec = SCENES.get(name, {})
    prompt = spec.get("prompt", name)
    if extra_style:
        prompt = prompt + "\n\nСТИЛЬ: " + (STYLE_SIMPLE if simple else STYLE)
    opts = {
        "aspect_ratio": ar or spec.get("aspect", "16:9"),
        "resolution": res or spec.get("res", "1K"),
    }
    if ref:
        opts["image_base64"] = b64(ref)
    q = pv.price(model, prompt, opts)
    print(f"[{name}] {model} quote = {q.get('priceRub')} ₽")
    files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                     name=name, max_price_rub=12)
    print("=>", files, "price:", st.get("priceRub"))
    return files


