"""S6-A «КПП Звёздного городка, рассвет» — широкий план (выбран Иваном 2026-10-17 «го А»).

Старый S6 (очередь к закрытой двери в синих сумерках) забракован: «это в банк, девяностые».
Новый: арка-проезд КПП, шлагбаум + турникет, будка с вахтёром, люди 2061 года идут к воротам
(термос, ребёнок за руку, рюкзак-планшет), рассвет с тёплой полосой у горизонта, снег и пар
от дыхания, светло и оптимистично. В кадре НЕТ текста (вывеска — чистая светлая панель).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая тёплая оптимистичная "
         "палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер.")

NOTEXT = ("Строго: НИКАКОГО текста, букв, цифр, слов, надписей и логотипов нигде в кадре — "
          "вывеска над аркой и таблички это чистые светлые панели без графики. "
          "Никаких водяных знаков.")

JOBS = {
 # A: широкий общий план — арка КПП, площадь перед ней, люди идут к воротам
 'a': ("Раннее утро, рассвет: низкое солнце даёт тёплую золотистую полосу у горизонта, небо "
       "светлое, чуть морозная дымка, лёгкий снег на асфальте и на плечах людей. Широкий общий "
       "план въезда в Звёздный городок 2061 года: над дорогой монументальная светлая "
       "железобетонная арка-проезд с широкой чистой панелью вывески, под ней шлагбаум и "
       "прозрачная кабина-турникет, рядом стеклянная будка вахтёра, в будке человек в форме. "
       "За аркой в глубине видны светлые корпуса городка и тонкая мачта с антенной. "
       "К воротам по широкому тротуару идут и подъезжают люди 2061 года: мужчина несёт "
       "термос, женщина ведёт за руку ребёнка в тёплой куртке, у подростка на спине "
       "плоский светящийся рюкзак-планшет, кто-то с сумкой через плечо. Люди идут спокойно, "
       "с надеждой, у многих пар от дыхания. Одежда — современная, чистая, спокойных цветов, "
       "никакой кожи и рванья. Атмосфера светлая, просторная, утро новой жизни."),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin7_s6_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plate s6%s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\n" + NOTEXT + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("flux-2", prompt,
                                     {"aspect_ratio": "16:9", "resolution": "2K"},
                                     outdir="assets/gen", name='prologfin7_s6_%s' % n,
                                     max_price_rub=12)
    print('plate s6%s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE),
                                          st.get('priceRub')))
print('готово')
