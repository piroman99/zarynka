# -*- coding: utf-8 -*-
"""S7 — «тысячи людей встали в очередь». После нового S6 (средний план у ворот с парой)
повторять тот же ракурс нельзя: берём МАСШТАБ — вид сверху на очередь-реку.
Модель gpt-image-2 (держит кириллицу, 2.70 ₽/кадр), сезон — весна (как в тексте).

A — верхний ракурс: очередь-река течёт по аллее к воротам, тысячи людей, ели, утро.
B — вид от ворот вниз по аллее: людская река уходит в глубину города, мачта на горизонте.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая тёплая оптимистичная "
         "палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер.")

TEXT = ("Строго: НИКАКОГО текста, букв, цифр и логотипов в кадре — вывески и таблички это "
        "чистые светлые панели без графики. Никаких водяных знаков.")

SEASON = ("ТЁПЛАЯ ПОЗДНЯЯ ВЕСНА, яркое весеннее солнце, ясное светлое небо, сочная молодая "
          "зелень, высокие ели вдоль аллеи, сухой чистый асфальт. НИКАКОГО снега и мороза.")

CROWD = ("ОГРОМНАЯ ОЧЕРЕДЬ людей — тысячи человек: она течёт непрерывной живой рекой по "
         "широкой аллее, изгибается, заполняет всю аллею и тротуары, уходит далеко за "
         "горизонт кадра. Люди 2061 года в чистой современной спокойной одежде, у многих "
         "папки с документами, кто-то с ребёнком, кто-то с термосом. Очередь — ГЛАВНОЕ в "
         "кадре, людей очень много, это всенародный порыв, а не редкая шеренга.")

FACES = ("Лица людей спокойные, нейтральные, сосредоточенные; никто не улыбается в камеру "
         "и не позирует. Никакой радости напоказ.")

JOBS = {
 'a': ("Утро, высокий ракурс сверху (съёмка с высокой точки над аллеей): видно, как "
       "гигантская очередь-река людей течёт по аллее к светлым воротам Звёздного городка, "
       "вдоль аллеи стоят высокие ели, в глубине кадра светлые корпуса городка. " + CROWD),
 'b': ("Утро, широкий общий план от ворот вниз по аллее: людская река уходит от ворот в "
       "глубину города и теряется за горизонтом, по сторонам высокие ели, вдали на "
       "горизонте тонкая мачта с антенной. " + CROWD),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 's7_gpt_%s_0.png' % n)
    if os.path.exists(out):
        print('s7 %s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\n" + FACES + "\n\n" + SEASON + "\n\n" + TEXT + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("gpt-image-2", prompt, {"aspect_ratio": "16:9"},
                                     outdir="assets/gen", name='s7_gpt_%s' % n,
                                     max_price_rub=6)
    print('s7 %s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE), st.get('priceRub')))
print('готово')
