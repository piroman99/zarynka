"""Пролог, кадры 6-8 (план 2026-10-25, «плотная сетка кадров»).

6. ХРОНИКА ПЕРВОГО ПОЛЁТА — архивный кадр: проводы Первой марсианской экспедиции.
   Плёнка заметно старше остальных кадров пролога (сильнее зерно, выцветшие тона).
7. ЦЕХ СБОРКИ — НОВАЯ ракета НЕДОСТРОЕНА (корпус до середины, леса, шпангоуты).
   Тот же цех, что в принятом S2 (`prologfin2_s2a_0.jpg`) — он идёт референсом.
   Без букв, номеров, плакатов, без телеги/крана на переднем плане.
8. БАССЕЙН-ГИДРОЛАБОРАТОРИЯ ЦПК — круглый бассейн 23 м в диаметре, 12 м глубиной,
   под водой полноразмерный макет орбитального модуля, космонавты в скафандрах.

Модель gpt-image-2, 16:9 1K = 4.06 ₽/кадр. Букв в кадре нет — по правилу Ивана.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

GEN = os.path.join(HERE, "assets", "gen")
REF_CEH = os.path.join(GEN, "prologfin2_s2a_0.jpg")       # принятый S2 = цех
REF_PAD = os.path.join(GEN, "prologfin2_s2b_0.jpg")       # принятый космодром (S2B, в сборку не шёл)

STYLE = (
    "ретро-футуристическая документальная кинохроника альтернативного 2061 года, кадр из фильма, "
    "16:9, киноплёнка с зерном и лёгкими царапинами, приглушённая холодная палитра, живописный "
    "фотореализм, светлый и оптимистичный мир будущего. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, логотипов и водяных знаков — ни на корпусе, "
    "ни на стенах, ни на приборах, ни на плакатах."
)

# ---------------------------------------------------------------- 6. хроника
P6 = (
    "Архивный кадр кинохроники: проводы Первой марсианской экспедиции. Гигантская белая "
    "многоступенчатая ракета СТОИТ ВЕРТИКАЛЬНО на стартовом столе (не лежит, не на транспорте), "
    "вокруг клубы белого пара от заправки, кабель-мачта и стартовые фермы, прожекторы на мачтах. "
    "На дальнем плане за ограждением — крошечные силуэты провожающих, человек двадцать, для "
    "масштаба; у кого-то в руках флажки. Раннее утро, низкое солнце в дымке, длинные тени. "
    "Кадр ЗАМЕТНО СТАРШЕ остальных кадров пролога: плёнка выцвела, тёпло-серые тона, крупное "
    "зерно, мелкие царапины и пылинки — как у съёмки за десятилетия до событий фильма. "
)

# ---------------------------------------------------------------- 7. цех
P7 = (
    "Огромный сборочно-испытательный цех, тот же, что на приложенном кадре (те же высокие "
    "стены, окна и фермы потолка). В центре на стапеле НЕДОСТРОЕННАЯ новая ракета: собран "
    "только нижний пояс корпуса — гладкие белые обечайки до середины высоты, выше — открытый "
    "каркас из шпангоутов и стрингеров, без обшивки, без верхних ступеней, головного обтекателя "
    "нет. Вокруг строительные леса, стяжки, кабели, сварочные аппараты; в глубине цеха вспышка "
    "сварки. Под потолком мостовой кран, прожекторы, дневной свет из высоких окон, пыль в "
    "воздухе. Внизу на полу катушки с кабелем, контейнеры, ящики; несколько инженеров в рабочих "
    "жилетах и касках — крошечные для масштаба. Никаких плакатов, растяжек и табличек. "
)

# ---------------------------------------------------------------- 8. бассейн
P8 = (
    "Зал гидролаборатории Центра подготовки космонавтов: КРУГЛЫЙ бассейн диаметром около "
    "двадцати трёх метров и двенадцати метров глубиной, прозрачная зеленовато-голубая вода. "
    "В глубине, метрах в шести под водой, — полноразмерный макет орбитального модуля: "
    "цилиндрический корпус, стыковочный узел, поручни, панели. Двое космонавтов в белых "
    "скафандрах с длинными шлангами работают у макета под водой, рядом водолаз-страхующий. "
    "По бортику круглые мостки с перилами, лебёдки, шланги, пульт; высокие светлые стены зала, "
    "прожекторы под потолком, блики и отражения на воде, лёгкая дымка над поверхностью. "
)

JOBS = [
    ("prolog_p6_firstflight", P6, [REF_PAD]),
    ("prolog_p7_ceh_new", P7, [REF_CEH]),
    ("prolog_p8_pool", P8, []),
]


def main(only=None, model="gpt-image-2"):
    for name, core, refs in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        refs = [r for r in refs if os.path.exists(r)]
        if refs:
            opts["input_base64"] = [gen.b64(r, max_w=1024) for r in refs]
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-22s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-22s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-22s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))
