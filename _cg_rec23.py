# -*- coding: utf-8 -*-
"""CG «двое в приёмной» (страница 23 по SCRIPT_CAST.md — приветствие).

Правки Ивана 2026-10-25: кабинет — наш (как в кадре приёмной), одежда Сергея —
со спрайта, за окном — весна и Звёздный городок, а не абстрактный «дневной свет».

Референсы: комната+Екатерина (принятый CG приёмной), Сергей (спрайт).
Модель gpt-image-2, 16:9 1K ≈ 4.06 ₽/кадр.
"""
import os, sys
import gen, pv

HERE = os.path.dirname(os.path.abspath(gen.__file__))
REF_ROOM = os.path.join(HERE, "assets", "gen", "cg_room_a__gpt-image-2_0.png")
REF_SERGEY = os.path.join(HERE, "assets", "gen", "sergey_eng_old__flux-2_0.jpg")

STYLE = (
    "Стиль и манера рисования — ТОЧНО как на первом приложенном кадре: тот же чистый лайн-арт, "
    "та же плоская cel-раскраска, та же приглушённая пастельная палитра, то же спокойное "
    "рассеянное освещение, та же толщина контуров. Ничего не менять в манере. "
)
ROOM = (
    "Интерьер — РОВНО тот же, что на первом приложенном кадре приёмной: высокие окна с видом на "
    "площадь и ели, дверь в коридор, письменный стол с зелёной папкой и ручкой, стеллаж с синими "
    "папками, плакат на стене, светло-голубые стены с облупившейся краской. Ничего не добавлять "
    "и не убирать из обстановки, никаких книжных шкафов, ламп с зелёным абажуром и красных "
    "плакатов. "
)
KATE = (
    "Екатерина Ивановна: женщина 50-55 лет, короткие седые ВЬЮЩИЕСЯ волосы до подбородка, яркие "
    "голубые глаза, мягкое доброе лицо с лёгкими морщинками, синий рабочий комбинезон на лямках "
    "поверх светлой рубашки (как на первом кадре). Она сидит на стуле с синей обивкой перед "
    "столом, спина прямая, руки на коленях, спокойная приветливая полуулыбка. "
)
SERGEY = (
    "Сергей Лихнецкий: мужчина 30 лет, короткие тёмные волосы с лёгкой сединой на висках, "
    "светлые глаза, лёгкая усталость на лице, чисто выбрит, ОДЕЖДА — как на втором приложенном "
    "кадре: светлая форменная рубашка с погонами на плечах и тёмный галстук. Он сидит за "
    "письменным столом, чуть привстал навстречу, вежливая дежурная улыбка, перед ним раскрытая "
    "папка с документами. "
)
WINDOW = (
    "За окнами — ЯСНЫЙ ВЕСЕННИЙ ДЕНЬ: голубое небо, ели и берёзы без листвы, низкие светлые "
    "корпуса Звёздного городка вдали, яркое солнце и длинные тени в комнате. Никакой зимы, "
    "снега, тумана и ночи. "
)
NO_TEXT = "Никаких надписей, букв, цифр и водяных знаков ни на плакате, ни на документах. "

SCENES = {
    # A — средний план через стол, оба в три четверти
    "cg_rec23_a": (
        "CG-кадр визуальной новеллы 16:9: двое в приёмной комиссии. " + ROOM + KATE + SERGEY
        + WINDOW +
        "РАКУРС: средний план со стороны окна, камера чуть выше уровня стола: Екатерина сидит "
        "слева в три четверти к камере, Сергей справа за столом, между ними по диагонали край "
        "стола с раскрытой папкой. Оба лица хорошо читаются. " + STYLE + NO_TEXT
    ),
    # B — шире: комната целиком, окна за Екатериной, Сергей за столом
    "cg_rec23_b": (
        "CG-кадр визуальной новеллы 16:9: двое в приёмной комиссии, общий план. " + ROOM + KATE
        + SERGEY + WINDOW +
        "РАКУРС: общий план от двери, по колено и выше: на переднем плане спинка стула "
        "Екатерины и её плечи, чуть дальше Сергей за письменным столом, за ней — высокие окна с "
        "весенним светом. " + STYLE + NO_TEXT
    ),
}


def main(only=None, model="gpt-image-2"):
    for name, prompt in SCENES.items():
        if only and name not in only:
            continue
        opts = {"aspect_ratio": "16:9", "resolution": "1K",
                "input_base64": [gen.b64(REF_ROOM, max_w=1024),
                                 gen.b64(REF_SERGEY, max_w=1024)]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-12s %s RUB" % (name, q.get("priceRub")), flush=True)
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-12s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-12s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:] or None, os.environ.get("CG_MODEL", "gpt-image-2"))
