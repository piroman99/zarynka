# -*- coding: utf-8 -*-
"""Скамейка v4: та же геометрия, но НОВАЯ и крашеная в тёмно-зелёный (вариант A Ивана).

Референс — `_sat/prop_bench_new_fixed2.png`: у него верная геометрия (все четыре ножки
стоят на наклонной линии земли, дальний конец дорисован целиком). Меняется только вид:
свежая краска вместо выветренного дерева.

Запуск: python3 _bench_prop_gen4.py [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv   # noqa: E402
from PIL import Image  # noqa: E402

REF = os.path.join(ROOT, '_sat', 'prop_bench_new_fixed2.png')

PROMPT = """Изолированный предмет на чистом БЕЛОМ фоне: НОВАЯ, аккуратно ПОКРАШЕННАЯ
парковая скамейка со спинкой. Людей нет.

ВНЕШНИЙ ВИД (главное):
— скамейка новая и ухоженная, покрашена ровной ТЁМНО-ЗЕЛЁНОЙ краской (цвет хвои,
  глубокий зелёный, местами с лёгким полуматовым блеском свежей краски);
— доски сиденья и спинки — дерево, покрашенное в тёмно-зелёный, ровные доски, чистые
  кромки, никаких сколов, облупившейся краски, плесени и грязи;
— боковины и ножки — литые чугунные, тёмные (почти чёрные), с простым спокойным
  профилем, без завитушек и без ржавчины;
— подлокотники есть, чугунные, того же тёмного тона.

ГЕОМЕТРИЯ (сохранить точно как на приложенном рисунке):
— камера сбоку-спереди, ближний торец СЛЕВА;
— линия земли под скамейкой поднимается слева направо примерно на 25 градусов;
— все ЧЕТЫРЕ ножки видны полностью, каждая СВОИМ НИЗОМ касается земли: нижние концы
  всех четырёх ножек лежат на одной наклонной линии, ни одна не висит в воздухе;
— ближняя передняя ножка самая крупная, дальняя передняя заметно короче;
— дальний (правый) конец дорисован целиком: у него есть и передняя, и задняя ножка,
  доски сиденья и спинки доходят до края, ничего не обрывается;
— по всей длине скамейка нарисована одинаково плотно, без бледных участков.

Стиль — акварель: прозрачные заливки, зерно бумаги, мягкие растушёвки, палитра
сдержанная, тени пыльно-синие.

БЕЗ тени на земле, БЕЗ фона, БЕЗ травы, БЕЗ надписей, БЕЗ рамки; предмет целиком
внутри кадра с полями белого."""


def main():
    dry = '--dry' in sys.argv
    im = Image.open(REF).convert('RGBA')
    canvas = Image.new('RGB', im.size, (255, 255, 255))
    canvas.paste(im, (0, 0), im)
    ref_path = os.path.join(ROOT, '_sat', 'prop_ref_v4.png')
    canvas.save(ref_path)
    print('референс:', os.path.relpath(ref_path, HERE), canvas.size)
    opts = {"aspect_ratio": "16:9", "resolution": "1K",
            "input_base64": [gen.b64(ref_path, max_w=1024)]}
    q = pv.price('gpt-image-2', PROMPT, opts)
    print('[quote]', q.get('priceRub'), 'RUB', flush=True)
    if dry:
        return
    files, st = pv.generate_to_files('gpt-image-2', PROMPT, opts, outdir='assets/gen',
                                     name='prop_bench_v4', max_price_rub=12)
    print('[ok] priceRub=%s' % st.get('priceRub'))
    for f in files:
        i2 = Image.open(f)
        print('  ', os.path.relpath(f, HERE), i2.size, os.path.getsize(f), 'B')


if __name__ == '__main__':
    main()
