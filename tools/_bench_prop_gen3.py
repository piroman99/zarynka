# -*- coding: utf-8 -*-
"""Скамейка-проп, третья попытка: главное — все четыре ножки СТОЯТ на земле.

Разбор первых двух (замеры):
  • старая (твоя): дальний конец прорисован только как спинка; сиденья и ножек там нет
    (маска кончается на x≈1194, ниже y≈450 пусто) — поэтому «растворяется»;
  • новая: дальняя передняя ножка нарисована на 123 px файла (≈14 см) ВЫШЕ линии земли —
    отсюда «правая сторона взлетела».
В обоих случаях виноват рисунок дальнего конца, а не посадка.

Промпт теперь описывает землю явно: линия земли поднимается вправо на ~25°, каждая
ножка доходит до неё, дальний конец дорисован целиком и меньше по размеру.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv   # noqa: E402
from PIL import Image  # noqa: E402

REF = os.path.join(ROOT, 'assets', 'sprites', 'prop_bench.png')

PROMPT = """Изолированный предмет на чистом белом фоне: старая деревянная парковая скамейка
со спинкой. Людей нет.

ГЕОМЕТРИЯ (главное, не путать):
— скамейка стоит на ровной земле, камера сбоку-спереди, ближний торец СЛЕВА;
— линия земли под скамейкой поднимается слева направо примерно на 25 градусов
  (дальний конец уходит в глубину);
— все ЧЕТЫРЕ ножки видны полностью и каждая СВОИМ НИЗОМ КАСАЕТСЯ земли: нижние концы
  всех четырёх ножек лежат на этой наклонной линии, ни одна ножка не висит в воздухе;
— ближняя передняя ножка — самая длинная и толстая, дальняя передняя заметно короче;
— дальний (правый) конец дорисован ЦЕЛИКОМ: у него есть и передняя, и задняя ножка,
  доски сиденья и спинки доходят до края, ничего не обрывается и не тает;
— по всей длине скамейка нарисована одинаково плотно, без бледных «эскизных» участков.

Материал: тёмное выветренное дерево, доски спинки и сиденья, потёртости, мелкие сколы.

Стиль — акварель: прозрачные заливки, зерно бумаги, мягкие растушёвки, палитра
серо-коричневая с пыльно-синими тенями, как на приложенном рисунке.

БЕЗ тени на земле, БЕЗ фона, БЕЗ травы, БЕЗ надписей, БЕЗ рамки; предмет целиком
внутри кадра с полями белого."""


def main():
    dry = '--dry' in sys.argv
    im = Image.open(REF).convert('RGBA')
    canvas = Image.new('RGB', im.size, (255, 255, 255))
    canvas.paste(im, (0, 0), im)
    ref_path = os.path.join(ROOT, '_sat', 'prop_ref_white.png')
    canvas.save(ref_path)
    opts = {"aspect_ratio": "16:9", "resolution": "1K", "input_base64": [gen.b64(ref_path, max_w=1024)]}
    q = pv.price('gpt-image-2', PROMPT, opts)
    print('[quote]', q.get('priceRub'), 'RUB', flush=True)
    if dry:
        return
    files, st = pv.generate_to_files('gpt-image-2', PROMPT, opts, outdir='assets/gen',
                                     name='prop_bench_v3', max_price_rub=12)
    print('[ok] priceRub=%s' % st.get('priceRub'))
    for f in files:
        i2 = Image.open(f)
        print('  ', os.path.relpath(f, HERE), i2.size, os.path.getsize(f), 'B')


if __name__ == '__main__':
    main()
