# -*- coding: utf-8 -*-
"""Сцена «аллея»: фон БЕЗ нарисованной скамейки (вариант B Ивана, 2026-11-22).

Зачем: в кадре `alley_b_0.jpg` скамейка нарисована в фоне и уходит в глубину
влево-вверх, а проп `bench2` нарисован в обратную сторону — отсюда «скамейка под
углом» и вся возня с PROP_FLIP. Чище убрать скамейку из фона совсем: она и так
отдельный слой-проп, движок её сам ставит.

Референс — сам `assets/gen/alley_b_0.jpg` (один референс = 0.45 ₽/кадр 16:9 1K):
он и композицию держит, и стиль (он же собран по `pilot_reception_0.png`).

Запуск:
    python3 _alley_bg_nobench.py --dry      # только цена
    python3 _alley_bg_nobench.py            # сгенерить
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv   # noqa: E402

REF = os.path.join(ROOT, 'assets', 'gen', 'alley_b_0.jpg')

CLEAN = (
    "ЛЮДЕЙ В КАДРЕ НЕТ (ни человека, ни силуэта, ни тени человека). "
    "НИКАКИХ НАДПИСЕЙ: ни табличек, ни указателей, ни афиш, ни плакатов, ни цифр, "
    "ни логотипов, ни водяных знаков. Весна: снега, наледи и сугробов нет."
)

NO_BENCH = (
    "ГЛАВНОЕ: в кадре НЕТ СКАМЕЙКИ. Убрать её полностью — ни сиденья, ни спинки, "
    "ни ножек, ни досок, ни одной перекладины, ни её тени. Там, где она стояла (слева "
    "на переднем плане), — ровный влажный асфальт с редкой хвоей, длинная тень от ели "
    "и блик солнца. Передний план слева оставить СВОБОДНЫМ и хорошо читаемым: ровное "
    "пустое место на асфальте."
)

KEEP = (
    "Всё остальное сохранить как на приложенном кадре: тот же ракурс и та же композиция. "
    "Высокие ели слева и справа, их тёмно-зелёные лапы заходят в кадр по краям. Аллея "
    "уходит в перспективу от камеры к кованым ажурным воротам в глубине, металл ворот "
    "сплетён в контур посадочного лунного модуля. Весеннее утро, солнце сбоку, длинные "
    "тени поперёк аллеи, влажный асфальт с бликами, много воздуха. Камера на уровне глаз, "
    "общий план."
)

STYLE = (
    "Стиль — акварель «акварельный космос»: прозрачные заливки по белой бумаге, видимое "
    "зерно бумаги, мягкие растушёвки и потёки, палитра пыльно-синий + охра + белый, много "
    "воздуха и света, лёгкая незавершённость по краям листа. Манера и палитра — ТОЧНО как "
    "на приложенном кадре. НЕ 3D, НЕ глянец, НЕ гуашь, НЕ фотореализм, НЕ аниме, "
    "НЕ мультфильм."
)

PROMPT = NO_BENCH + " " + KEEP + " " + CLEAN + "\n\nСТИЛЬ: " + STYLE


def main(model="gpt-image-2", name="alley_b_nobench"):
    dry = "--dry" in sys.argv
    print("ref:", os.path.relpath(REF, HERE), "есть:", os.path.exists(REF), flush=True)
    ref = gen.b64(REF, max_w=1024)
    opts = {"aspect_ratio": "16:9", "resolution": "1K", "input_base64": [ref]}
    q = pv.price(model, PROMPT, opts)
    print("[quote] %s RUB" % q.get("priceRub"), flush=True)
    if dry:
        return
    files, st = pv.generate_to_files(model, PROMPT, opts, outdir="assets/gen",
                                     name="%s__%s" % (name, model), max_price_rub=12)
    print("[ok] priceRub=%s" % st.get("priceRub"), flush=True)
    for f in files:
        from PIL import Image
        im = Image.open(f)
        print("  ", os.path.relpath(f, HERE), im.size, im.mode, os.path.getsize(f), "B", flush=True)


if __name__ == "__main__":
    main()
