    # сколько говорит каждый — сразу видно, что стоит денег в озвучке
    stat = {}
    for i, who, tx in rows:
        n, ch = stat.get(who, (0, 0))
        stat[who] = (n + 1, ch + len(tx))
    print('\nпо голосам (сегментов / знаков):')
    for k in sorted(stat, key=lambda x: -stat[x][1]):
        print('  %-10s %4d / %6d' % (k, stat[k][0], stat[k][1]))
