def build():
    lines = io.open(STORY, encoding='utf-8').read().split('\n')
    rows, bad, unlabelled = [], [], []
    for i, raw in enumerate(lines, 1):
        t = raw.strip()
        if not t or not t.strip('* '):        # пусто или разделитель «* * *»
            continue
        segs = segments(t)
        speech = [s for s in segs if s[0] in ('speech', 'mix')]
        # разворачиваем 'mix' обратно в два сегмента (реплика + вставка)
        roles = []
        for kind, tx in segs:
            if kind == 'mix':
                for k2, t2 in tx:
                    roles.append((k2, t2))
            else:
                roles.append((kind, tx))
        sp = [r for r in roles if r[0] == 'speech']
        want = CAST.get(i, [])
        if len(sp) != len(want):
            bad.append((i, len(sp), len(want), t[:70]))
            want = want + ['?'] * (len(sp) - len(want))
        k = 0
        for kind, tx in roles:
            if kind == 'speech':
                who = want[k] if k < len(want) else '?'
                k += 1
                if who == '?':
                    unlabelled.append(i)
            else:
                who = A
            rows.append((i, who, tx))
    return rows, bad, unlabelled


def main():
    rows, bad, unlabelled = build()
