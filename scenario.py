def dump(dest=None):
    dest = dest or os.path.join(os.path.dirname(os.path.abspath(__file__)), "scenario.json")
    data = {
        "title": TITLE,
        "subtitle": SUBTITLE,
        "by": BY,
        "cast": CAST,
        "scenes": SCRIPT,
    }
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    total = sum(len(s["shots"]) for s in SCRIPT)
    print(f"scenario: {len(SCRIPT)} сцен, {total} узлов -> {dest}")
    return dest


