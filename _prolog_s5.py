# фикс случайной тур.строки в промпте A
JOBS['a'] = JOBS['a'].replace(' açıkly', '').replace(' açıkно и празднично', ' светло и празднично')

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin5_s5_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plate s5%s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\n" + NOTEXT + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("flux-2", prompt, {"aspect_ratio": "16:9", "resolution": "2K"},
                                     outdir="assets/gen", name='prologfin5_s5_%s' % n, max_price_rub=12)
    print('plate s5%s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE), st.get('priceRub')))
