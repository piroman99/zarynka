"""Правки Ивана по сцене «аллея» (2026-11-05): скамейка отдельно от спрайта.

Что не так по его словам:
  1) у сидящего спрайта скамейка «длиной со стул» — должна быть длинной;
  2) скамейка вибрирует вместе со спрайтом поэта — значит она не должна быть
     частью анимированного спрайта: это ОТДЕЛЬНЫЙ статичный слой (prop);
  3) эмоций на скамейке мало (было 3);
  4) на CG парная скамейка стоит углом к дороге — «так не бывает»: длина скамейки
     должна идти ВДОЛЬ аллеи, как бордюр.

Отсюда три вида ассетов:
  • bench_long — длинная скамейка, отдельный кадр, акварель в стиле фона
    (референс — сама скамейка с фона alley_b, вырезанная в `_bench_ref.jpg`);
  • sit2_* — сидящий поэт БЕЗ скамейки, полная фигура (до ступней), 6 эмоций;
  • cg_muza2 — CG «Муза», скамейка вдоль аллеи.

Запуск: python3 _alley_fix2.py [bench sit_neutral cg ...] [--dry]
"""
