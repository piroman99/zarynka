def main(only):
    dry = '--dry' in sys.argv
    jobs = [('bench_long', BENCH_PROMPT,
             {'aspect_ratio': '2:1', 'resolution': '1K',
              'input_base64': [gen.b64(BENCH_REF, max_w=640)]})]
    for k, e in SIT_EXPR.items():
        jobs.append((k.replace('sit_', 'sit2_'), SIT_LOCK + SIT_POSE + e,
                     {'aspect_ratio': '3:4', 'resolution': '1K',
                      'input_base64': [gen.b64(POET, max_w=1024)]}))
    jobs.append(('cg_muza2', CG2_PROMPT,
                 {'aspect_ratio': '16:9', 'resolution': '1K',
                  'input_base64': [gen.b64(ALLEY, max_w=1024),
                                   gen.b64(POET, max_w=640),
                                   gen.b64(KATE, max_w=640)]}))
    tot = 0.0
    for name, prompt, opts in jobs:
        if only and name not in only:
            continue
        q = pv.price('gpt-image-2', prompt, opts)
        tot += float(q.get('priceRub') or 0)
        print('[quote] %-14s %s RUB' % (name, q.get('priceRub')), flush=True)
        if dry:
            continue
        try:
            files, st = pv.generate_to_files('gpt-image-2', prompt, opts, outdir='assets/gen',
                                             name=name, max_price_rub=12)
            print('[ok]    %-14s %s' % (name, [os.path.basename(f) for f in files]), flush=True)
        except Exception as e:  # noqa: BLE001
            print('[fail]  %-14s %s' % (name, str(e)[:160]), flush=True)
    print('[sum] ~%.2f RUB' % tot)


if __name__ == '__main__':
    only = [a for a in sys.argv[1:] if not a.startswith('-')]
    main(only or None)
