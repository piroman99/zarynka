# -*- coding: utf-8 -*-
"""Пролог, кадр 6 (`p6`) — ПЕРЕСБОРКА: ЛУННАЯ СТАНЦИЯ (не Марс, композита нет).

Иван 2026-11-04: «P6 — композит не надо. И не нужна там марсианская охра, это лунная
станция. P6 пересобери как лунную станцию».

Смысл кадра — реплика из L[7]: «…гнаться за третьей американской экспедицией или
четвёртой китайской смысла нет — лучше лунную базу до ума доведите». То есть база на
Луне есть, но она НЕ ДОВЕДЕНА ДО УМА: часть модулей недостроена, леса, кран, мешки
с реголитом вместо защиты, свежая сварка. Палитра лунная — серый реголит, чёрное небо,
белые модули, тёплый свет только в окнах; никакой марсианской охры.

Референс — наш собственный арт лунной станции из тизера `assets/gen/ok_space_station_0.jpg`
(белые цилиндрические модули под куполом, тарелка антенны): база рисуется В КАДРЕ, а не
вклеивается силуэтом (композит `_p6_base.py` отклонён Иваном 2026-11-04).

Варианты:
  A — общий: база в среднем плане на ровной равнине, Земля в чёрном небе, колея ровера.
  B — средний: ряд модулей вблизи, фигура в скафандре для масштаба, недостроенная секция.

Букв/эмблем/флагов в кадре нет (правило Ивана). gpt-image-2, 16:9 1K ≈ 4.06 ₽/кадр.
Запуск:
    python3 _prolog_p6_luna.py [p6luna_a p6luna_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen
import pv

REF = os.path.join(HERE, 'assets', 'gen', 'ok_space_station_0.jpg')

STYLE = (
    "Ретро-футуристическая документальная кинохроника альтернативного 2061 года, 16:9, "
    "кадр из архивного фильма о лунной программе, киноплёнка: мелкое зерно, редкие "
    "царапины и пылинки, лёгкая расфокусировка по краям, приглушённая холодная палитра "
    "(серый, белый, сине-чёрный), живописный фотореализм. "
    "НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, НЕ постер. "
    "НИКАКОГО текста, надписей, букв, цифр, номеров, эмблем, флагов, логотипов и водяных "
    "знаков — ни на модулях, ни на скафандрах, ни на технике."
)

CORE = (
    "Лунная база землян на поверхности Луны, вид снаружи. Серый реголитовый простор, "
    "мелкие камни и пыль, резкие длинные тени от низкого солнца, чёрное небо без "
    "облаков и без звёздной россыпи, у горизонта Земля — небольшой серо-голубой диск "
    "с белыми облаками. Сама база: ряд белых цилиндрических жилых модулей с рёбрами "
    "жёсткости, приземистый купол с широкой смотровой полосой, мачта с круглой "
    "тарелкой антенны, короткие переходы-тамбуры на опорах, обсыпанные реголитом "
    "мешки-маты по бокам модулей. База НЕ ДОСТРОЕНА: у дальнего конца ряда открытый "
    "каркас новой секции — шпангоуты без обшивки, строительные леса, подъёмный кран "
    "на гусеницах, бухты кабеля, ящики и контейнеры вокруг, у стыка модулей искры "
    "сварки. Тёплый жёлтый свет только в двух-трёх окнах-иллюминаторах, остальное — "
    "холодный лунный день. Палитра СТРОГО лунная: серый, белый, сине-чёрный; никакой "
    "красно-оранжевой марсианской пыли, никакой охры."
)

A = CORE + (
    " Композиция: общий план, камера чуть выше уровня глаз, база в средней части кадра "
    "и левее, справа и на переднем плане — пустая равнина; от базы к камере тянется "
    "колея колёсного ровера, у правого края — край неглубокого кратера. Ощущение "
    "архивной съёмки со штатива на штативе: камера чуть завалена, край кадра мягкий."
)

B = CORE + (
    " Композиция: средний план, камера на уровне человека, ряд модулей и леса "
    "недостроенной секции занимают правую половину кадра, слева уходит в глубину "
    "равнина и там же диск Земли в небе. У входа в ближний модуль стоит крошечная "
    "фигура космонавта в светлом скафандре со шлангом, для масштаба. Следы на пыли. "
    "Съёмка с рук, чуть смазано, зерно и царапины плёнки."
)

JOBS = [("p6luna_a", A), ("p6luna_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    ref = gen.b64(REF, max_w=1024)
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K", "input_base64": [ref]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-10s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-10s %s RUB -> %s" % (name, st.get("priceRub"),
                                               os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-10s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))
