# -*- coding: utf-8 -*-
"""Пролог, кадр 11 (`s5a`) — «лозунг облетел страну»: городская площадь с тумбами.

Решение Ивана 2026-11-01: «11 ну давай попробуем» → вариант (ii) из
PROLOG_BRIEF_9_12.md: обычная городская площадь с плакатными тумбами, БЕЗ
выставочной аллеи с павильоном (и без ракеты — запрещена с 2026-10-14).

В кадре НЕТ букв: все надписи даёт титр-слой движка (pg.ovl). Поэтому у самой
крупной тумбы/стенда поверхность ПУСТАЯ — туда ляжет полоса лозунга. Стенд
разворачиваем к камере: плоская полоса на плоской поверхности читается, на
круглом столбе в перспективе — нет.

Два варианта подачи (на выбор Ивана):
  A — камера на уровне глаз, двое клеят плакат крупно слева, площадь в глубину;
  B — общий план площади, группа тумб по центру, больше людей и воздуха.

gpt-image-2, 16:9 1K = 4.06 ₽/кадр. Запуск:
    python3 _prolog_s5a.py [s5a_a s5a_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

STYLE = (
    "Ретро-футуристическая документальная кинохроника альтернативного 2061 года, 16:9, "
    "кадр из фильма, киноплёнка с зерном и лёгкими царапинами, приглушённая тёплая "
    "палитра, живописный фотореализм. День, весна, яркое солнце, длинные косые тени. "
    "НЕ мультфильм, НЕ аниме, НЕ 3D-рендер. НИКАКОГО текста, надписей, букв, цифр, "
    "логотипов и водяных знаков — ни на плакатах, ни на тумбах, ни на флагах, ни на "
    "стенах, ни на транспорте. Все плакаты и афиши ПУСТЫЕ, чистые, без букв."
)

CORE = (
    "Многолюдная городская площадь альтернативного 2061 года. Плакатные тумбы — "
    "круглые афишные столбы — и рядом НИЗКИЙ ШИРОКИЙ СТЕНД-ВИТРИНА, развёрнутый "
    "плоско к камере, его лицевая поверхность пустая, чистая, без букв. Двое людей "
    "клеят плакат: руки, валик, ведро с клеем, свежий пустой лист на тумбе. Прохожие "
    "приостановились и читают, кто-то несёт ребёнка на плечах. В глубине — "
    "электроавтобус без рельсов, флаги на столбах, жилые корпуса в три-пять этажей, "
    "деревья с молодой листвой. Лица нейтральные, будничные, спокойные: это не митинг, "
    "транспарантов и флажков в руках нет. "
)

NEG = (
    "ЗАПРЕЩЕНО: ракета и космический корабль в кадре, выставочный павильон с колоннадой, "
    "небоскрёбы и телебашни, река и мост, рекламные пилоны с надписями, крупный "
    "городской силуэт на горизонте."
)

A = CORE + (
    "Композиция: камера на уровне глаз, тумбы и двое клеящих — крупно в левой трети "
    "переднего плана, стенд-витрина справа от них, площадь уходит в глубину."
)
B = CORE + (
    "Композиция: общий план площади, группа тумб и стенд-витрина по центру кадра, "
    "вокруг люди, много воздуха и света, в глубине улица и корпуса."
)

JOBS = [("s5a_a", A), ("s5a_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + NEG + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K"}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-8s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name="%s__%s" % (name, model), max_price_rub=12)
            print("[OK] %-8s %s RUB -> %s" % (name, st.get("priceRub"),
                                              os.path.relpath(files[0], HERE)), flush=True)
        except Exception as e:
            print("[FAIL] %-8s %s" % (name, str(e)[:240]), flush=True)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args or None, os.environ.get("PROLOG_MODEL", "gpt-image-2"))
