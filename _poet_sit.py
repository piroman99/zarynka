# -*- coding: utf-8 -*-
"""СИДЯЩИЙ поэт (3 эмоции) + CG «Муза» — правка Ивана 2026-11-04.

Иван: «1.B 2.B. Давай попробуем CG на музу» — значит:
  • кадр аллеи остаётся B (уже стоит, 0 ₽);
  • поэт на скамейке СИДИТ (3 эмоции, 0.45 ₽ каждая);
  • плюс CG на пиковую страницу «Муза» (0.45 ₽).

Сидящий спрайт: лицо и одежда держатся референсом `poet2_b_0.png` (принятый вид),
поза меняется на сидячую, кадр — по колено, чтобы низ картинки совпал с уровнем
скамейки. Эмоции: upset (лицо в ладонях), neutral (поднял голову), interested
(смотрит на Екатерину, живой взгляд).

CG: акварель, референсы — кадр аллеи (это МЕСТО), спрайт поэта (его лицо),
спрайт Екатерины (её лицо). Момент — «— Муза, — юноша покраснел и отвернулся».

Запуск: python3 _poet_sit.py [sit_upset sit_neutral sit_interested cg_muza] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv  # noqa: E402

GEN = os.path.join(HERE, 'assets', 'gen')
POET = os.path.join(GEN, 'poet2_b_0.png')
KATE = os.path.join(GEN, 'kate_overalls_0.png')
ALLEY = os.path.join(GEN, 'alley_b_0.jpg')

LOCK = (
    "СОХРАНИ ТОЧНО того же персонажа: молодой мужчина двадцати пяти лет, ОКРУГЛОЕ мягкое "
    "лицо, полные щёки, округлый подбородок, короткий нос, обычные серые глаза (не аниме), "
    "ЛЁГКАЯ НЕБРИТОСТЬ на щеках и над губой, тёмные длинные неухоженные волосы до плеч, "
    "тёмная куртка поверх светлой рубашки, высокий и нескладный. "
    "Манера рисования — мягкая живопись с видимыми мазками, как на приложенном спрайте. "
    "НЕ аниме, НЕ манга, НЕ cel-shading, НЕ 3D, НЕ фото."
)

SIT = (
    " Он СИДИТ на старой деревянной скамейке со спинкой, чуть ссутулившись, колени вместе. "
    "Кадр — по колено: видно голову, торс, руки и бёдра. Фигура по центру кадра, "
    "ровный однотонный светло-серый фон, без реквизита и без тени на фон."
)

EXPR = {
    'sit_upset': " Лицо закрыто ладонями, локти на коленях — только волосы и пальцы видны.",
    'sit_neutral': (" Он отнял ладони от лица и поднял голову, смотрит перед собой "
                    "потерянно и непонимающе."),
    'sit_interested': (" Он смотрит в сторону и чуть вверх — живой, заинтересованный "
                       "взгляд, брови приподняты, голова повёрнута в профиль на три четверти."),
}

CG_PROMPT = (
    "Кадр из визуальной новеллы: аллея в Звёздном городке весной. "
    "На старой деревянной скамейке между высоких еловых лап сидят двое: слева пожилая "
    "женщина пятидесяти пяти лет — кудрявые седые как снег волосы, мягкое лицо в добрых "
    "морщинах, яркие голубые глаза, синий рабочий комбинезон на лямках, тёплая полуулыбка, "
    "она чуть наклонилась к собеседнику и положила руку ему на плечо; справа молодой "
    "мужчина двадцати пяти лет — длинные тёмные неухоженные волосы до плеч, округлое "
    "мягкое лицо, лёгкая небритость, большие серые глаза, он покраснел и отвернулся, "
    "смотрит в сторону, плечи поникли, тёмная куртка поверх светлой рубашки. "
    "За скамейкой в глубине — кованые ажурные ворота, металл сплетён в контур посадочного "
    "лунного модуля. Весеннее утро, солнце сбоку, длинные тени от елей поперёк аллеи, "
    "влажный асфальт. Место и свет — РОВНО как на приложенном кадре аллеи, ничего не "
    "менять в декорациях. Лица — как на приложенных спрайтах персонажей. "
    "Стиль: акварель, прозрачные заливки по белой бумаге, видимое зерно, пыльно-синий + "
    "охра + белый, мягкие растушёвки. НЕ 3D, НЕ глянец, НЕ фотореализм, НЕ аниме. "
    "НИКАКИХ НАДПИСЕЙ в кадре."
)


def main(only=None):
    dry = '--dry' in sys.argv
    jobs = []
    for k, e in EXPR.items():
        jobs.append((k, LOCK + SIT + e, {'aspect_ratio': '3:4', 'resolution': '1K',
                                         'input_base64': [gen.b64(POET, max_w=1024)]}))
    jobs.append(('cg_muza', CG_PROMPT, {'aspect_ratio': '16:9', 'resolution': '1K',
                                        'input_base64': [gen.b64(ALLEY, max_w=1024),
                                                         gen.b64(POET, max_w=640),
                                                         gen.b64(KATE, max_w=640)]}))
    for name, prompt, opts in jobs:
        if only and name not in only:
            continue
        q = pv.price('gpt-image-2', prompt, opts)
        print('[quote] %-15s %s RUB' % (name, q.get('priceRub')), flush=True)
        if dry:
            continue
        try:
            files, st = pv.generate_to_files('gpt-image-2', prompt, opts, outdir='assets/gen',
                                             name=name, max_price_rub=12)
            print('[ok] %-15s %s' % (name, [os.path.basename(f) for f in files]), flush=True)
        except Exception as e:  # noqa: BLE001
            print('[fail] %-15s %s' % (name, str(e)[:140]), flush=True)


if __name__ == '__main__':
    only = [a for a in sys.argv[1:] if not a.startswith('-')]
    main(only or None)
