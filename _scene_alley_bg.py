# -*- coding: utf-8 -*-
"""Сцена «аллея у ворот» (эп-1, после приёмной): фоны, 3 кадра.

Текст `assets/story.txt`:
  стр. 71 — «Расстроенная Екатерина Ивановна вышла из дверей приемной комиссии. Яркое
            весеннее солнце резануло по глазам… спустилась по широким ступеням и
            повернула на аллею, обсаженную с двух сторон елями.»
  стр. 73 — «Недалеко от кованых ажурных ворот, где металл причудливо сплетался в контур
            посадочного лунного модуля, на скамейке между зеленых еловых лап сидел юноша.»

Кадры:
  steps_a  — двери приёмной + широкие ступени + весеннее солнце (переходный кадр)
  alley_a  — скамейка между еловых лап, в глубине кованые ворота с контуром лунного
             модуля (средний план, скамья в центре-слева)
  alley_b  — шире: аллея уходит в перспективу к воротам, скамья на переднем плане слева

Правила: людей в кадре НЕТ (спрайты движок кладёт сверху), НИКАКИХ надписей,
весна (снега нет), стиль — «акварельный космос» как у приёмной (референс-кадр
`assets/pilot/pilot_reception_0.png`).

Запуск:
    python3 _scene_alley_bg.py [steps_a alley_a alley_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv  # noqa: E402

REF = os.path.join(HERE, 'assets', 'pilot', 'pilot_reception_0.png')

STYLE = (
    "Стиль — акварель «акварельный космос»: прозрачные заливки по белой бумаге, видимое "
    "зерно бумаги, мягкие растушёвки и потёки, палитра пыльно-синий + охра + белый, много "
    "воздуха и света, лёгкая незавершённость по краям листа. Манера рисования и палитра — "
    "ТОЧНО как на приложенном кадре интерьера приёмной. НЕ 3D, НЕ глянец, НЕ гуашь, "
    "НЕ фотореализм, НЕ аниме, НЕ мультфильм."
)

CLEAN = (
    "ЛЮДЕЙ В КАДРЕ НЕТ (ни одного человека, ни силуэта, ни тени человека). "
    "НИКАКИХ НАДПИСЕЙ: ни табличек, ни указателей, ни афиш, ни плакатов, ни цифр, "
    "ни логотипов, ни водяных знаков. Весна: снега, наледи и сугробов нет."
)

STEPS = (
    "Вид от дверей приёмной комиссии: за спиной остаются высокие двустворчатые двери "
    "старого административного корпуса, перед ними широкая каменная лестница вниз, "
    "ступени уходят из кадра к нижнему краю. Яркое весеннее солнце бьёт в камеру сбоку, "
    "свет заливает ступени, на камне длинные косые тени от балясин и от козырька. "
    "По сторонам лестницы молодая трава и низкий кустарник, в глубине кадра аллея и ели. "
    "Камера на уровне глаз человека, стоящего на верхней ступени. "
) + CLEAN

ALLEY_A = (
    "Аллея в Звёздном городке, обсаженная с двух сторон высокими елями: тёмно-зелёные "
    "еловые лапы заходят в кадр слева и справа, между ними воздух и свет. На среднем плане "
    "чуть левее центра стоит старая деревянная скамейка со спинкой, пустая, между двух "
    "еловых лап; на сиденье и на земле под ней хвоя. За скамейкой в глубине — кованые "
    "ажурные ворота, металл сплетён в контур посадочного лунного модуля, за воротами "
    "дальний забор и крыши корпусов. Асфальт ещё влажный после утра, на нём блики солнца. "
    "Весеннее утро, солнце сбоку, длинные тени от елей лежат поперёк аллеи. "
    "Камера на уровне глаз, средний план. "
) + CLEAN

ALLEY_B = (
    "Широкий кадр аллеи в Звёздном городке: аллея уходит в перспективу от камеры к кованым "
    "ажурным воротам в глубине, металл ворот сплетён в контур посадочного лунного модуля. "
    "Слева и справа высокие ели, их лапы заходят в кадр по краям. На переднем плане слева "
    "старая деревянная скамейка со спинкой, пустая, наполовину в тени ели. Влажный асфальт, "
    "блики солнца, длинные тени поперёк аллеи. Весеннее утро, много воздуха. "
    "Камера на уровне глаз, общий план. "
) + CLEAN

JOBS = [("steps_a", STEPS), ("alley_a", ALLEY_A), ("alley_b", ALLEY_B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    ref = gen.b64(REF, max_w=1024)
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + STYLE
        opts = {"aspect_ratio": "16:9", "resolution": "1K", "input_base64": [ref]}
        try:
            q = pv.price(model, prompt, opts)
            print("[quote] %-9s %s RUB" % (name, q.get("priceRub")), flush=True)
            if dry:
                continue
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name=name, max_price_rub=12)
            print("[ok] %-9s %s" % (name, [os.path.basename(f) for f in files]), flush=True)
        except Exception as e:  # noqa: BLE001
            print("[fail] %-9s %s" % (name, e), flush=True)


if __name__ == "__main__":
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    main(only or None)
