"""S2 РАЗБИТ на два кадра (правка заказчика 2026-10-13):
  S2A — ЦЕХА: ракету собирают (стапель, фермы, кран, сварка, люди-точки).
  S2B — КОСМОДРОМ под прожекторами: готовый гигант на стартовом столе.
Ракета — СВЕРХТЯЖ на весь кадр (была «слишком маленькая для Марса»).
Плашки: assets/gen/prologfin_s2a_0.jpg, prologfin_s2b_0.jpg (кэш — повторно не платим).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с лёгким зерном, светлая приглушённая палитра, "
         "живописный фотореализм, ощущение грандиозности и оптимизма. НЕ мультфильм, НЕ аниме, "
         "НЕ 3D-рендер, НИКАКОГО текста, надписей, букв, цифр, логотипов и водяных знаков.")

JOBS = {
    's2a': ("Внутри огромного светлого сборочного цеха ракетного завода 2061 года: гигантская "
            "многоступенчатая ракета-носитель собирается на стапеле — кольцевые фермы, строительные "
            "леса, мостовой кран сверху, сварка с искрами, белые панели корпуса с красными поясами; "
            "ракета заполняет кадр по высоте, у подножия крошечные фигурки рабочих в касках для "
            "масштаба; высокие окна, светлые пролёты, лёгкая дымка."),
    's2b': ("Ночной космодром 2061 под прожекторами: гигантская белая многоступенчатая ракета-носитель "
            "вертикально стоит на стартовом столе, рядом кабель-заправочная башня и фермы обслуживания, "
            "лучи прожекторов скрещиваются в небе, вдали крошечные силуэты людей и техники для масштаба, "
            "ракета уходит вверх за край кадра, синие сумерки, торжественно и величественно."),
}

for n, desc in JOBS.items():
    out = os.path.join(HERE, 'assets', 'gen', 'prologfin_%s_0.jpg' % n)
    if os.path.exists(out):
        print('plate %s: есть (кэш) %d B' % (n, os.path.getsize(out)))
        continue
    prompt = desc + "\n\nСТИЛЬ: " + CHRON
    files, st = pv.generate_to_files("flux-2", prompt, {"aspect_ratio": "16:9", "resolution": "2K"},
                                     outdir="assets/gen", name='prologfin_%s' % n, max_price_rub=12)
    print('plate %s -> %s  price=%s' % (n, os.path.relpath(files[0], HERE), st.get('priceRub')))
print('готово')
