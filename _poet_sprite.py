# -*- coding: utf-8 -*-
"""Спрайт ПОЭТА (эп-1): длинноволосый юноша, которого Лихнецкий отправил восвояси.

Текст: «Следующим оказался длинноволосый поэт, высокий, нескладный, с тоской в больших
серых глазах, готовый долететь до Марса в поисках своей музы» (стр. 19) и сцена на
скамейке у ворот («юноша», «я поэт», краснеет).

Стиль — как у каста (`gen.STYLE`, VN/galge), поясной спрайт на ровном светло-сером фоне,
чтобы `cutout()` в `_vn2_build.py` срезал фон без каймы. Цвет волос в тексте не назван —
беру тёмно-каштановый (сказать Ивану, если не так).

Варианты:
  A — волосы до плеч, простая куртка, руки опущены
  B — длиннее, до лопаток, рубашка с воротником, чуть более «нескладный», сутулится

Запуск:
    python3 _poet_sprite.py [poet_a poet_b] [--dry]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen  # noqa: E402
import pv  # noqa: E402

LOOK = (
    "Молодой мужчина 24 лет, ПОЭТ: очень длинные тёмно-каштановые волосы, прямые, "
    "неухоженные, спадают на плечи; высокий и нескладный, узкие плечи, чуть сутулится; "
    "худое бледное лицо, тонкие черты, БОЛЬШИЕ СЕРЫЕ ГЛАЗА с тоской и растерянностью, "
    "лёгкая щетина не нужна — гладко выбрит; выражение — расстроенное, потерянное, "
    "готовое расплакаться. Одежда: простая, неброская, слегка мешковатая — "
    "тёмная куртка поверх светлой рубашки, без знаков и надписей. "
    "Поясной спрайт визуальной новеллы (видно до середины бедра), фигура по центру, "
    "смотрит в камеру, ровный однотонный светло-серый фон, без реквизита и без тени на фон."
)

A = LOOK + " Волосы распущены и лежат на плечах ровными прядями, руки свободно опущены."
B = LOOK + (" Волосы длиннее, до лопаток, часть пряди падает на лицо; воротник рубашки "
            "неряшливо расстёгнут, плечи опущены сильнее — поза потерянного человека.")

JOBS = [("poet_a", A), ("poet_b", B)]


def main(only=None, model="gpt-image-2"):
    dry = "--dry" in sys.argv
    for name, core in JOBS:
        if only and name not in only:
            continue
        prompt = core + "\n\nСТИЛЬ: " + gen.STYLE
        opts = {"aspect_ratio": "3:4", "resolution": "1K"}
        q = pv.price(model, prompt, opts)
        print("[quote] %-7s %s RUB" % (name, q.get("priceRub")), flush=True)
        if dry:
            continue
        try:
            files, st = pv.generate_to_files(model, prompt, opts, outdir="assets/gen",
                                             name=name, max_price_rub=12)
            print("[ok] %-7s %s" % (name, [os.path.basename(f) for f in files]), flush=True)
        except Exception as e:  # noqa: BLE001
            print("[fail] %-7s %s" % (name, str(e)[:160]), flush=True)


if __name__ == "__main__":
    only = [a for a in sys.argv[1:] if not a.startswith("-")]
    main(only or None)
