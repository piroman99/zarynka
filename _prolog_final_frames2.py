# -*- coding: utf-8 -*-
"""Проба финальных кадров пролога v2 — БЕЗ ракеты в Звёздном городке (правка заказчика).
Звёздный городок = ЦПК: тренажёры, центрифуга, гидролаборатория, городок. Ракеты — Байконур.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pv

CHRON = ("ретро-футуристическая документальная кинохроника альтернативного 2061 года, "
         "кадр из фильма, 16:9, киноплёнка с зерном и лёгкими царапинами, приглушённая "
         "холодная палитра, живописный фотореализм. НЕ мультфильм, НЕ аниме, НЕ 3D-рендер, "
         "НИКАКОГО текста, надписей, букв, цифр, логотипов и водяных знаков.")
ANIME = ("стиль японской визуальной новеллы (galge), как в «Бесконечном лете» и Katawa Shoujo: "
         "чистый выразительный лайн-арт, плоская cel-раскраска, мягкие градиенты, тёплая "
         "пастельная палитра, спокойное рассеянное освещение. НЕ фотореализм, НЕ 3D, "
         "НИКАКОГО текста, надписей, букв и логотипов.")

CORE = ("Звёздный городок — небольшой закрытый городок Центра подготовки космонавтов в "
        "Подмосковье поздним вечером: низкие жилые дома с тёплым светом окон, длинный "
        "корпус центра подготовки, купол гидролаборатории, вращающаяся центрифуга, "
        "несколько силуэтов людей, синие сумерки. ВАЖНО: НЕ ракета, НЕ космодром, "
        "НЕ стартовый стол — только городок и центр подготовки.")

JOBS = [("prolog_s2_cin_0", CORE, CHRON), ("prolog_s2_anime_0", CORE, ANIME)]
for name, core, style in JOBS:
    prompt = core + "\n\nСТИЛЬ: " + style
    opts = {"aspect_ratio": "16:9", "resolution": "2K"}
    files, st = pv.generate_to_files("flux-2", prompt, opts, outdir="assets/gen",
                                     name=name, max_price_rub=12)
    print(f"OK {name} -> {os.path.relpath(files[0], HERE)}  price={st.get('priceRub')}")
